-- Отметка «про этот ответ поддержки человеку уже написали в Telegram».
-- Нужна, чтобы серия ответов админа подряд не превращалась в серию сообщений
-- бота: отправку разрешаем не чаще одного раза в окно (ClaimSupportReplyNotify),
-- а чтение переписки пользователем отметку снимает — следующий ответ снова
-- дойдёт сразу.
--
-- Отдельный файл под один ALTER — правило проекта: SQLite применяет миграцию
-- целиком, и упавший ALTER посреди файла оставил бы схему полуприменённой
-- (Migrate игнорирует только "duplicate column name").
ALTER TABLE support_threads ADD COLUMN reply_notified_at DATETIME;
