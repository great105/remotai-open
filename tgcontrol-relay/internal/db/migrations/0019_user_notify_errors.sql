-- Отдельный выключатель сообщений «в терминале мелькнула ошибка» (команда
-- /notify). До этой колонки ошибки ехали вместе с вопросами агента под одним
-- флагом tg_notify, хотя настройка обещала только «вопросы агента»: погасить
-- шум от красных строк тестов можно было лишь вместе с уведомлениями, ради
-- которых канал и существует.
--
-- По умолчанию ВЫКЛЮЧЕНО: событие error приходит с ПК без самой строки ошибки
-- (см. internal/pty/manager.go — setEvent(EventError, at, "", "")), поэтому
-- сообщение сообщает только «где», а важно это или обычный FAIL в тестах —
-- человек всё равно узнаёт, лишь открыв терминал. Кто хочет — включает в /notify.
--
-- Отдельный файл под один ALTER — см. комментарий в 0008_user_notify.sql.
ALTER TABLE users ADD COLUMN tg_notify_errors INTEGER NOT NULL DEFAULT 0;
