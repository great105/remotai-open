--
-- Отдельный файл под один ALTER — правило проекта: SQLite применяет миграцию
-- целиком, и упавший ALTER посреди файла оставил бы схему полуприменённой
-- (Migrate игнорирует только "duplicate column name").
ALTER TABLE users ADD COLUMN tg_notify INTEGER NOT NULL DEFAULT 1;
