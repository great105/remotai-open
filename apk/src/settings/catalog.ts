/**
 * Раскладка каталога настроек по экранам — правило, а не разметка.
 *
 * ЗАЧЕМ. Каталог (`/api/settings/catalog`, `internal/web/api_settings_catalog.go`)
 * описывает каждую настройку словами: что делает, какой тип, какие значения
 * допустимы и опасно ли менять. Его читает AI-агент — а человек не видел его
 * НИКОГДА: клиент к этой ручке не обращался вовсе (проверено 09.08.2026).
 * Отсюда дыры: сторож зависшего VPN и доступ с других устройств аккаунта живут
 * на компьютере, агент про них знает, а в приложении их нет ни в каком виде.
 *
 * ПРАВИЛО «КОПИЙ НАСТРОЕК НЕТ НИГДЕ» (решение 2.51.0) остаётся в силе: если у
 * настройки уже есть своё место, здесь показывается ДВЕРЬ туда, а не второй
 * орган управления. Два тумблера на одну настройку разъезжаются на первой
 * правке — так когда-то разъехались два списка своих команд.
 *
 * СЛЕДСТВИЕ, ради которого это вынесено в данные: новая настройка на сервере
 * появляется в приложении САМА. Не попала в карту мест — покажется в общей
 * секции с пояснением, а не потеряется молча.
 */

/** Одна настройка так, как её отдаёт компьютер. */
export interface SettingSpec {
  key: string;
  title: string;
  hint: string;
  type: "bool" | "string" | "int" | "path" | string;
  options?: string[];
  risk: "safe" | "dangerous" | string;
  /** Что это такое и как работает — абзацами, показываются при раскрытии. */
  details?: string[];
  value?: unknown;
}

/** Где настройка живёт, если у неё есть своё место в приложении. */
export interface SettingHome {
  /** Маршрут экрана, где ей управляют. */
  route: string;
  /** Название места словами человека — для строки «Настроить в …». */
  placeKey: string;
}

/**
 * Карта «у этой настройки есть свой хозяин».
 *
 * Список короткий намеренно: сюда попадает только то, у чего в приложении
 * ДЕЙСТВИТЕЛЬНО есть полноценный орган управления. Записать сюда настройку «на
 * будущее» — значит спрятать её от человека совсем.
 */
export const SETTING_HOMES: Record<string, SettingHome> = {
  // ПУСТО, и это решение владельца (09.08.2026): «если уж у нас настройки —
  // чтобы всё можно было в них настраивать, а не переходить по экранам, и
  // только там, где реально необходимо перейти».
  //
  // Двери отсюда вели в «Агенты» и в «Панель ПК» — и обе были лишними.
  // Безопасное меняется прямо здесь через apply; автозапуск — своей ручкой
  // (см. OWNER_SAVERS); а то, что из приложения не меняется вовсе, честнее
  // объяснить на месте, чем отправлять человека на экран, где он тоже ничего
  // не сделает. Именно это и раздражало: «нажимаешь автозапуск — переходит на
  // панель ПК и как-то дублируется».
  // ⚠ Сюда НЕЛЬЗЯ вписывать «/settings»: этот список показывается НА экране
  // настроек, и дверь вела бы саму на себя. Так и вышло 09.08.2026 с рабочей
  // папкой, папкой входящих и уведомлениями — три строки-двери в никуда, а
  // рядом, в «Расширенных», те же настройки вторым экземпляром. Владелец это
  // и заметил: «в расширенных дублируется часть настроек».
};

/**
 * Что показать в общей секции и как.
 *
 * `editable` — безопасная настройка без своего места: ею управляют прямо здесь.
 * `readonly` — опасная без своего места: `POST /api/settings/apply` меняет
 *   только безопасное (граница власти, решение владельца), поэтому обещать
 *   переключатель нельзя. Показываем значение и говорим, чем менять.
 * `elsewhere` — у настройки есть свой экран, ведём туда.
 */
export type SettingPlacement =
  | { kind: "editable"; spec: SettingSpec }
  | { kind: "readonly"; spec: SettingSpec }
  | { kind: "elsewhere"; spec: SettingSpec; home: SettingHome };

/**
 * Опасные настройки, у которых ЕСТЬ человеческий путь из приложения.
 *
 * Граница власти («опасное меняет только владелец») стоит на `apply` — она про
 * AI-АГЕНТА, который сидит в терминале и последствий не увидит. У человека же
 * автозапуск переключается своей ручкой (`POST /api/system/autostart`) и всегда
 * переключался — просто из настроек до 09.08.2026 туда вела дверь в «Панель
 * ПК» вместо тумблера.
 *
 * Список именно белый: `web_port`, `peer_access` и `cloud` сюда не попадут —
 * из приложения их менять нечем, и обещать переключатель было бы враньём.
 */
export const OWNER_EDITABLE = new Set(["autostart"]);

export function placeSetting(spec: SettingSpec): SettingPlacement {
  const home = SETTING_HOMES[spec.key];
  if (home) return { kind: "elsewhere", spec, home };
  if (spec.risk === "dangerous" && !OWNER_EDITABLE.has(spec.key)) return { kind: "readonly", spec };
  return { kind: "editable", spec };
}

/** Весь каталог, разложенный по способу показа; порядок сервера сохраняется. */
export function placeCatalog(list: SettingSpec[]): SettingPlacement[] {
  return list.filter((spec) => !!spec && !!spec.key).map(placeSetting);
}

/** Человеческая запись значения: тумблеры — словами, пустое — прочерком. */
export function settingValueText(spec: SettingSpec, words: { on: string; off: string; unset: string }): string {
  if (spec.type === "bool") return spec.value ? words.on : words.off;
  const value = spec.value;
  if (value === null || value === undefined || value === "") return words.unset;
  return String(value);
}

/**
 * Что отправить на сервер. Ручка принимает СТРОКУ (её же присылает агент), а
 * разбирает по типу сама — второй разборщик на клиенте разошёлся бы с ним.
 */
export function settingWireValue(spec: SettingSpec, next: unknown): string {
  if (spec.type === "bool") return next ? "true" : "false";
  return String(next ?? "");
}
