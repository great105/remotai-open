/**
 * Лицо сервера: плашка, имя, адрес, подпись — одно на все экраны.
 *
 * Один и тот же SSH-сервер рисовали две разные карточки. В списке машин
 * (/infrastructure) — фиолетовая плашка «▰», имя и моноширинный адрес; в
 * разделе «SSH-серверы» (/ssh) — имя без плашки, а адрес показывался ТОЛЬКО у
 * сервера со своим именем: без имени адрес сам становился заголовком, и один
 * объект назывался на двух экранах по-разному («prod» против «root@prod»).
 * Человек читал два облика как два разных списка.
 *
 * Возвращаем ФРАГМЕНТ, а не обёртку. На /infrastructure строка сервера — это
 * сам <button>, на /ssh — <div> с кнопками «Подключиться», «Файлы», «✎», «🗑»
 * внутри. Общая обёртка дала бы либо кнопку внутри кнопки (невалидная разметка,
 * ломается клавиатура и скринридер), либо потерю тапа по строке.
 *
 * Различаться экранам разрешено НАБОРОМ ДЕЙСТВИЙ и подробностями, а не обликом:
 * бейдж источника и подпись «когда подключались» приходят слотами badge и meta,
 * а не своей разметкой.
 */
import type { ReactNode } from "react";

export function ServerIdentity({ name, address, badge, meta, children }: {
  /** Имя сервера. Без своего имени сервер зовётся адресом — одинаково везде. */
  name: string;
  /** user@host[:порт] — то, что человек напечатал бы в ssh. */
  address: string;
  /** Откуда сервер взялся: из ~/.ssh/config или заведён руками. */
  badge?: ReactNode;
  /** Подпись под адресом: когда подключались, сколько раз. */
  meta?: ReactNode;
  /**
   * Строки, которые есть только у раздела «SSH-серверы»: ключ, замок пароля,
   * связанная машина, теги. Стоят в той же колонке под подписью — иначе в
   * flex-строке /ssh они встали бы рядом с именем, а не под ним.
   */
  children?: ReactNode;
}) {
  return (
    <>
      <span className="infra-device-icon server" aria-hidden>{"▰"}</span>
      <span className="infra-server-main">
        <span className="infra-server-name">{name}{badge}</span>
        {/* У сервера без своего имени заголовок и есть адрес — печатать его
            второй раз незачем. */}
        {address && address !== name ? <span className="infra-server-addr">{address}</span> : null}
        {meta ? <span className="infra-server-meta">{meta}</span> : null}
        {children}
      </span>
    </>
  );
}
