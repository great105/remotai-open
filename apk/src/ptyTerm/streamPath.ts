import { t } from "@tgcontrol/shared";
// Сборка ЛОКАЛЬНОГО пути стрима (то, что агент откроет у себя: /ws/pty/<id>).
//
// Почему это отдельный модуль, а не пара строк на месте вызова. Путь до агента
// идёт двумя разными дорогами, и они по-разному относятся к параметрам запроса:
//
//   LAN:     ws://<пк>/ws/pty/<id>?initData=…            — параметры видит агент
//   облако:  wss://<релей>/v1/client/<dev>/stream?jwt=…&path=%2Fws%2Fpty%2F<id>
//                                                        — агент видит только path
//
// Из-за этого дописывание «?resume=…» к ГОТОВОМУ адресу работало на LAN и молча
// пропадало в облаке: в облачном адресе знак вопроса уже есть, resume уходил
// параметром РЕЛЕЮ, а тот про него ничего не знает. Замер 02.08.2026: 33 стрима
// из 33 приходили полным снимком по 512 КиБ (≈18 МБ мобильного трафика за два
// часа) и с маркером reset, то есть с потерей прокрученной истории на экране.
//
// Поэтому параметры прибиваются к ЛОКАЛЬНОМУ пути здесь, до выбора дороги.

/**
 * Параметры, которые РЕЛЕЙ пропускает до агента. Зеркало белого списка
 * `streamQueryAllowed` из tgcontrol-relay/internal/server/ws_stream.go.
 *
 * ⚠ ЖИВОЙ ОТКАЗ 12.08.2026, стоил телефону всех терминалов. Клиент начал
 * просить кадр экрана флагом `?screen=1`. Релей проверяет параметры пути по
 * ЗАКРЫТОМУ списку (иначе через путь можно подсунуть агенту что угодно), не
 * нашёл `screen` и ответил `400 invalid stream path` за 2 мс — соединение
 * умирало на релее, до компьютера не доходило вовсе. Замер: 35 отказов подряд
 * с 11:15:23 до 11:22:18, в журнале агента за это время НИ ОДНОЙ попытки.
 *
 * Почему это не поймали раньше: проверяли на localhost, где релея нет и путь
 * едет прямо агенту. Облачный путь — единственный, которым телефон реально
 * пользуется, — не проверялся ни разу.
 *
 * Отсюда правило: новый параметр здесь появляется ТОЛЬКО вместе с правкой
 * релея и ТОЛЬКО после его выкатки. Всё остальное, что клиент хочет сообщить
 * агенту, передаётся сообщением ВНУТРИ уже открытого соединения — там нет ни
 * релея, ни согласования версий.
 */
export const STREAM_QUERY_ALLOWED = ["resume"] as const;

/** Параметры локального стрима. Пустые и неопределённые значения опускаются. */
export type StreamParams = Record<string, string | number | undefined | null>;

/**
 * Собрать локальный путь стрима с параметрами запроса.
 * `localStreamPath("/ws/pty/a1", { resume: "ep:12" })` → `/ws/pty/a1?resume=ep%3A12`
 */
export function localStreamPath(path: string, params?: StreamParams): string {
  if (!params) return path;
  const parts: string[] = [];
  for (const [key, raw] of Object.entries(params)) {
    if (raw === undefined || raw === null || raw === "") continue;
    if (!(STREAM_QUERY_ALLOWED as readonly string[]).includes(key)) {
      // Не молча выбрасываем, а падаем на месте: параметр вне белого списка
      // релея означает, что в облаке терминал не откроется ВООБЩЕ (400), и
      // узнать об этом на localhost невозможно. Пусть ломается в тесте, а не
      // у человека в руках.
      throw new Error(t("ui.streampath.m00749111b5", { p0: (key) }));
    }
    parts.push(`${encodeURIComponent(key)}=${encodeURIComponent(String(raw))}`);
  }
  if (!parts.length) return path;
  return path + (path.includes("?") ? "&" : "?") + parts.join("&");
}

/**
 * Значение параметра resume: «поток этой эпохи у меня есть до этого байта».
 * Пустая эпоха означает первый коннект — просить нечего.
 */
export function resumeParam(epoch: string, offset: number): string | undefined {
  if (!epoch) return undefined;
  return `${epoch}:${offset}`;
}

/** С какой версии агент разбирает запрос ВНУТРИ пути стрима. */
const RESUME_IN_PATH_SINCE = [2, 49, 11];

/**
 * Умеет ли агент этой версии принять параметры внутри пути стрима.
 *
 * Спрашивать обязательно, и вот почему. До 2.49.11 агент склеивал локальный
 * адрес простым «путь + ?initData=…», поэтому путь с собственным запросом давал
 * ДВА знака вопроса: initData уезжал внутрь значения resume, локальный
 * обработчик отвечал отказом авторизации, и терминал не открывался вовсе. То
 * есть цена ошибки здесь не «лишний трафик», а неработающий экран — поэтому
 * непонятную версию (пусто, dev-сборка) считаем НЕ умеющей.
 *
 * Проверка нужна только облачному пути: в LAN клиент говорит с агентом
 * напрямую, и там запрос всегда доезжал.
 */
export function agentSupportsResumeInPath(version?: string | null): boolean {
  const parsed = /^v?(\d+)\.(\d+)\.(\d+)/.exec((version || "").trim());
  if (!parsed) return false;
  for (let i = 0; i < RESUME_IN_PATH_SINCE.length; i++) {
    const part = Number(parsed[i + 1]);
    if (part !== RESUME_IN_PATH_SINCE[i]) return part > RESUME_IN_PATH_SINCE[i];
  }
  return true;
}
