/**
 * Код привязки сервера, замеченный в выводе терминала.
 *
 * `remotai pair` на новом сервере печатает код, ссылку на бота и QR — и
 * предлагает взять ТЕЛЕФОН. Но команду эту чаще всего запускают из терминала
 * Remotai на компьютере, где человек уже вошёл в свой аккаунт: живая реакция
 * владельца на такой экран — «а я захожу с компьютера)». Брать телефон, чтобы
 * подтвердить то, что видишь на экране, — лишний шаг на ровном месте.
 *
 * Поэтому терминал сам замечает код и предлагает кнопку. Правило чистое:
 * строка вывода на входе, код на выходе — проверяется без React.
 */

/** Код привязки: две группы по четыре символа, без похожих S/5 (алфавит релея). */
const PAIR_CODE_RE = /\b([A-Z0-9]{4}-[A-Z0-9]{4})\b/;

/**
 * Заголовок, который печатает именно `remotai pair`. Без него кодом привязки
 * считался бы любой похожий набор символов в выводе (номер заказа, хеш, кусок
 * лога), и кнопка «Привязать этот сервер» всплывала бы посреди чужой работы.
 */
const PAIR_HEADER = "привязка сервера";

/** Строка, после которой предложение неактуально: код уже подтверждён. */
const PAIR_DONE = /привязан|подтверждено|уже привязан/i;

/** Отмена (Ctrl+C) — человек передумал, кнопку убираем. */
const PAIR_CANCELLED = /remotai:\s*отменено/i;

/**
 * Ищет в хвосте вывода код привязки, который ещё имеет смысл подтверждать.
 * Возвращает пустую строку, если предлагать нечего.
 *
 * @param tail последние строки терминала (уже без ANSI)
 */
export function pairCodeInOutput(tail: string): string {
  if (!tail) return "";
  const lower = tail.toLowerCase();
  const headerAt = lower.lastIndexOf(PAIR_HEADER);
  if (headerAt < 0) return "";

  // Смотрим только НА ТО, что напечатано после заголовка: прошлая привязка в
  // истории терминала уже неактуальна.
  const block = tail.slice(headerAt);
  if (PAIR_DONE.test(block) || PAIR_CANCELLED.test(block)) return "";

  // Код ищем в строке, которая его называет, — иначе им мог бы стать кусок QR
  // или адрес. Строку «Код: XXXX-XXXX» печатает сам remotai pair.
  for (const line of block.split("\n")) {
    if (!/код\s*:/i.test(line)) continue;
    const m = PAIR_CODE_RE.exec(line.toUpperCase());
    if (m) return m[1];
  }
  return "";
}
