/**
 * Шов между историей снапшота и кадром экрана: сколько строк писать и сколько
 * пустых строк дописать, чтобы в scrollback клиента оказалось РОВНО столько
 * строк, сколько прислал сервер.
 *
 * Задача. Зеркало экрана отдаёт `history` = S строк scrollback ПЛЮС R текущих
 * видимых строк, и заявляет их числом (`hist_lines` = S+R) и геометрией
 * (`screen_rows` = R). Клиент печатает историю в чистый терминал, а сверху
 * кладёт абсолютно адресованный кадр. Кадр начинается со стирания экрана,
 * которое в xterm НЕ сдвигает строки в scrollback, — то есть всё, что к
 * приходу кадра осталось на видимом экране, пропадает без следа.
 *
 * Что ломалось (внешний аудит 13.08.2026, находки T-001 и T-019). Клиент писал
 * все S+R строк в терминал СВОЕЙ высоты R′ и полей `screen_rows`/`hist_lines`
 * не читал вовсе. Счёт прокруток сходится только при R′ = R:
 *
 *   R′ = R  → в scrollback уходит ровно S строк — как задумано;
 *   R′ > R  → уходит S−(R′−R): последние строки истории остаются на экране и
 *             гибнут под стиранием кадра. Пропадают САМЫЕ СВЕЖИЕ строки, те,
 *             что прямо над экраном, — в прокрутке появляется дыра на стыке;
 *   R′ < R  → уходит S+(R−R′): верхние строки видимого экрана снапшота
 *             оседают в истории И перерисовываются кадром — видимый дубль.
 *
 * Разница высот не гипотетическая: кадр снимается в геометрии PTY (минимум по
 * всем зрителям), а печатается в высоту конкретного окна.
 *
 * Решение — арифметика, а НЕ ресайз. Подгонять свой терминал под геометрию
 * снапшота (приём VS Code forceExactSize) в этом проекте запрещено: размер
 * терминала на телефоне управляет размером PTY на компьютере, и такой ресайз
 * возвращает качели размеров с полной перерисовкой TUI (2.56.4, боевой лог
 * `48x30 → 48x10`). Вместо этого:
 *
 *   1. печатаем ТОЛЬКО scrollback-часть истории — первые S = hist_lines −
 *      screen_rows строк. Видимые строки печатать незачем: кадр перерисует
 *      экран целиком и самодостаточно;
 *   2. дописываем ровно столько переводов строки, чтобы все S строк
 *      оказались в scrollback, — сколько именно, считаем ПО ИЗМЕРЕНИЮ уже
 *      напечатанного (baseY и позиция курсора), а не по формуле от длины
 *      текста. Измерение переживает перенос длинных строк, двойную ширину
 *      emoji и любое расхождение подсчёта ячеек между Go и xterm.js;
 *   3. после этого проверяем baseY: сошлось — шов точный, не сошлось — знаем
 *      об этом (T-019: сервер шлёт hist_lines «для контроля приёма», а клиент
 *      не проверял ничего).
 *
 * Чистое правило: ни xterm, ни DOM, ни сети — проверяется тестом без React
 * (общий приём проекта, см. snapshotHistory/altScroll/tapGuard).
 */

/** Разделитель строк истории — тот же, которым их склеивает зеркало. */
const HISTORY_EOL = "\r\n";

/**
 * Брать ли присланную историю ВМЕСТО той, что у терминала уже есть.
 *
 * Присланная история применяется через полный сброс (RIS) — иначе её строки
 * легли бы поверх существующих дублем. Значит выбор всегда РАЗМЕН: своя
 * прокрутка стирается, чужая печатается. Он выгоден не всегда.
 *
 * Замер на живых сессиях владельца 13.08.2026 (экран 31 строка, прокрутка
 * СВЕРХ видимого экрана):
 *
 *   Kimi   — 500 строк (потолок зеркала);
 *   Claude — 49, 13, 4, 4, 4, 0, 0, 0.
 *
 * Разница не в нашем коде, а в самих агентах: Kimi и Codex печатают ПОТОКОМ,
 * строки уходят вверх, и зеркало честно копит их. Claude Code перерисовывает
 * экран НА МЕСТЕ — вверх не уходит ничего, копить нечего. Прокрутка Claude
 * всегда собиралась из другого источника: реплея кольца, который приходит при
 * открытии терминала. Меняя её на четыре строки зеркала, мы забирали у человека
 * почти всю историю — снаружи это «в Kimi вижу всё, в Claude только часть».
 *
 * Отсюда правило, записанное в проекте ещё после отката 2.57.4: **любая чистка
 * реплея обязана ответить, чем Claude Code будет скроллиться после неё.**
 * Здесь она отвечает: своей же прокруткой, которую мы больше не стираем.
 *
 * Сравнение честно только при ОДИНАКОВОЙ ШИРИНЕ. Строки зеркала логические, а
 * baseY клиента считает физические: у́же зеркала — длинные строки заворачиваются,
 * и своя история кажется больше, чем есть. Ширина обычно совпадает (PTY идёт по
 * самому узкому зрителю, и это как раз телефон), а вот высота расходится
 * постоянно — на неё смотреть не нужно, число строк от неё не зависит.
 *
 * ⚠ Про измерение своей прокрутки — см. вызывающего: мерить обязательно
 * `buffer.normal`, а не `buffer.active` (у alt-screen baseY ноль по определению,
 * и полноэкранный TUI выглядел бы терминалом без истории), и обязательно ПОСЛЕ
 * того, как прежний вывод разобран.
 */
export function shouldReplaceHistory(o: {
  /** Строк прокрутки в присланной истории (scrollbackLineCount). */
  serverScrollback: number;
  /** Строк прокрутки у терминала сейчас (buffer.normal.baseY). */
  localScrollback: number;
  /** Совпала ли ширина снапшота с шириной терминала. */
  sameWidth: boolean;
}): boolean {
  if (o.serverScrollback <= 0) return false; // менять не на что
  // Ширина не сошлась — числа несравнимы. Тогда меняем, только если своей
  // истории нет вовсе: терять нечего, а пустая прокрутка хуже любой.
  if (!o.sameWidth) return o.localScrollback <= 0;
  return o.serverScrollback > o.localScrollback;
}

/**
 * Сколько строк присланной истории относится к scrollback, а не к видимому
 * экрану. Возвращает −1, если сервер не дал внятных чисел (старый агент, поля
 * отсутствуют) — тогда вызывающий обязан остаться на прежнем поведении и
 * напечатать историю целиком.
 */
export function scrollbackLineCount(histLines: unknown, screenRows: unknown): number {
  if (typeof histLines !== "number" || typeof screenRows !== "number") return -1;
  if (!Number.isFinite(histLines) || !Number.isFinite(screenRows)) return -1;
  if (histLines <= 0 || screenRows < 0) return -1;
  const s = Math.floor(histLines) - Math.floor(screenRows);
  if (s < 0 || s > Math.floor(histLines)) return -1;
  return s;
}

/**
 * Первые `n` строк истории, каждая с завершающим переводом строки (включая
 * последнюю: курсор должен встать на СВОЮ строку, а не в конец текста).
 * Пустой результат, если печатать нечего.
 *
 * Если строк в тексте меньше заявленного — берём сколько есть: врать себе о
 * числе напечатанных строк нельзя, на нём стоит весь дальнейший расчёт.
 */
export function takeScrollbackLines(history: string, n: number): { text: string; lines: number } {
  if (n <= 0 || !history) return { text: "", lines: 0 };
  const all = history.split(HISTORY_EOL);
  const take = Math.min(n, all.length);
  return { text: all.slice(0, take).join(HISTORY_EOL) + HISTORY_EOL, lines: take };
}

/**
 * Сколько переводов строки дописать, чтобы в scrollback оказалось ровно
 * `target` строк.
 *
 * Курсор стоит в строке `cursorY` (от нуля) экрана высотой `rows`, в
 * scrollback сейчас `baseY` строк. Ниже курсора остаётся `rows−1−cursorY`
 * строк: пока курсор идёт по ним, прокрутки нет; каждый следующий перевод
 * строки сдвигает в scrollback ровно одну строку. Отсюда
 *
 *     k = (target − baseY) + (rows − 1 − cursorY)
 *
 * Значения меряются у живого терминала ПОСЛЕ записи истории, поэтому формула
 * не зависит ни от переносов длинных строк, ни от ширины символов.
 */
export function fillerRows(target: number, baseY: number, cursorY: number, rows: number): number {
  if (!(rows > 0)) return 0;
  const need = target - baseY;
  if (need <= 0) return 0; // строк в scrollback уже не меньше нужного
  const below = Math.max(0, rows - 1 - cursorY);
  return need + below;
}
