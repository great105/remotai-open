/**
 * Автоответы терминала — то, что xterm шлёт в PTY САМ, без человека.
 *
 * Признак «агент не отвечает» опирается на время ввода ЧЕЛОВЕКА: живой агент
 * отвечает на клавишу эхом мгновенно, и молчание дольше 8 с после ввода — это
 * уже тишина, а не задержка (01.09.2026, две зависшие сессии Claude Code).
 * Но `term.onData` срабатывает не только на клавиши: xterm отвечает
 * приложению на его же запросы —
 *
 *   • отчёт о фокусе `ESC[I` / `ESC[O` (режим ?1004h; Claude Code его
 *     включает — видно в каждом кадре экрана `?1004h`);
 *   • позиция курсора `ESC[<row>;<col>R` в ответ на `ESC[6n`;
 *   • атрибуты устройства `ESC[?…c` / `ESC[>…c` в ответ на DA1/DA2;
 *   • состояние режима `ESC[?…$y` (DECRPM), статус `ESC[0n`;
 *   • ответы на OSC-запросы цвета `ESC]10;…BEL` / `ESC]11;…BEL`.
 *
 * Ответа на них от агента не бывает по определению. Пока они считались
 * вводом человека, каждый переход в приложение (отчёт о фокусе) через 8 с
 * поднимал бейдж «Агент не отвечает» на живом простаивающем Claude Code —
 * скриншот владельца 03.09.2026, 10:33: «когда просто ничего не происходит,
 * он пишет „агент не отвечает“».
 *
 * Чистое правило без xterm и DOM — проверяется тестом в node.
 */

const ESC = "\x1b";

/** Ответы CSI: фокус, позиция курсора, атрибуты устройства, режимы, статус. */
const CSI_REPLY = "\\x1b\\[(?:I|O|\\d+;\\d+R|\\?\\d+(?:;\\d+)*c|>\\d+(?:;\\d+)*c|\\?\\d+;\\d+\\$y|\\d+;\\d+\\$y|0n|3n)";
/** Ответы OSC (цвета и т. п.): ESC ] <номер> ; … BEL | ESC \ */
const OSC_REPLY = "\\x1b\\]\\d+;[^\\x07\\x1b]*(?:\\x07|\\x1b\\\\)";
/**
 * Вся строка — один или несколько ответов подряд (пачка при серии запросов).
 * Одним регулярным выражением, а не делением по ESC: у OSC терминатор
 * ST = ESC \ сам начинается с ESC.
 */
const ONLY_REPLIES = new RegExp(`^(?:${CSI_REPLY}|${OSC_REPLY})+$`);

/**
 * Истина, если `data` из `term.onData` — автоответ терминала приложению, а
 * не действие человека.
 */
export function isTerminalAutoReply(data: string): boolean {
  if (!data || data[0] !== ESC) return false;
  return ONLY_REPLIES.test(data);
}
