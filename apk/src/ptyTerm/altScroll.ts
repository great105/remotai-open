/**
 * Каналы прокрутки полноэкранного приложения и последовательности для них.
 *
 * ЖИВАЯ ЖАЛОБА 12.08.2026: «в этом терминале вообще не скроллится». Замер по
 * `remotai.log`: 682 попытки прокрутки за сутки, все `alt=true mouse=any`,
 * режим 1006 агентом включён — то есть формат отчёта колеса верный, а экран не
 * двигается. Тогда мы объяснили это человеку словами и на том остановились.
 *
 * ⚠ ЧЕГО МЫ НЕ ЗНАЛИ: у Claude Code есть ДРУГОЙ канал прокрутки, и он
 * документирован вендором. В fullscreen-режиме разговор листают `PgUp`/`PgDn`
 * и `Ctrl+Home`/`Ctrl+End`; колесо мыши там же названо отдельной настройкой
 * (`CLAUDE_CODE_SCROLL_SPEED`) и работает не всегда.
 *
 * Лестница каналов — от самого безопасного к последнему:
 *
 *   1. `viewport` — своя история xterm, ничего никуда не шлём;
 *   2. `wheel` — alt-screen с mouse-tracking: отчёт колеса (vim, htop, less);
 *   3. `page` — PgUp/PgDn для AI-агента (Claude Code — документировано);
 *   4. `arrows` — alt-screen без mouse-tracking и БЕЗ агента: less и man;
 *   5. `none` — сказать человеку правду и предложить экспорт вывода.
 *
 * С 13.09.2026 ВЫБОР ступени живёт в navigationDecision.ts (одно правило с
 * приоритетом до побочных эффектов, план стабилизации ST-02). Здесь остались
 * замер потока, последовательности и бюджет страниц.
 *
 * ⚠ ПОЧЕМУ СТРЕЛКИ НЕЛЬЗЯ АГЕНТУ. У чат-агента ↑/↓ — это перебор истории
 * запросов: набранный промпт подменяется старым сообщением, отменить нечем.
 * PgUp/PgDn такой беды не несут — они не трогают строку ввода.
 *
 * ⚠ ОДНО СООБЩЕНИЕ, А НЕ N. Раньше каждая строка прокрутки уходила отдельным
 * `ws.send`: одно нажатие ⇈ при rows=30 — это 150 отдельных сообщений по ~12
 * полезных байт при ~36 байтах накладных. Последовательность собирается
 * целиком и уходит одним куском.
 */

/**
 * С какой глубины СВОЯ история терминала считается настоящей.
 *
 * Замер на живых сессиях владельца 13.08.2026: у Codex и Kimi реплей даёт
 * 500–1097 строк, у Claude Code снапшот — 0–79. Порог посередине разделяет их с
 * запасом и, в отличие от «экрана накопленного», не зависит от высоты окна,
 * которая на телефоне скачет от клавиатуры (48x31 → 48x11).
 */
export const OWN_HISTORY_LINES = 200;

/**
 * Чья это история — терминала или самого приложения.
 *
 * ⚠ Порог `OWN_HISTORY_LINES` сам по себе на этот вопрос НЕ отвечает, и оба
 * промаха видны на живых сценариях (повторный аудит 2.57.12, T25712-02):
 *   • свежий Codex/Kimi накопил 120 строк — 120 < 200, и `PgUp` уходил бы
 *     ВНУТРЬ агента, хотя история у терминала настоящая;
 *   • Claude, запущенный в терминале, где до него шелл напечатал 300 строк —
 *     300 ≥ 200, и жест крутил бы чужой шелловый мусор вместо разговора Claude.
 *
 * Отвечает ЗАМЕР ПОТОКА: приложение, которое печатает, гонит строки вверх, а
 * приложение, которое перерисовывает экран на месте, — нет. Числа 13.08.2026
 * (переводов строки на 32 КБ): codex 617, kimi 176, claude 3–29.
 *
 * ⚠ С 06.09 признак агентов уже НЕ разделяет (Codex 1,9 при пороге 2, Claude
 * 0,4–3,1), поэтому с 13.09 он лишь СЛАБАЯ эвристика: решает только там, где
 * нет ни объявленного реестром канала, ни наблюдения ответа
 * (navigationDecision.ts). Имя агента признаком не является: за четыре месяца
 * Kimi и Claude поменялись ролями.
 */
export type HistoryOwner = "terminal" | "application" | "unknown";

/** Строк scrollback на килобайт вывода, выше которых поток считается прокручиваемым. */
export const STREAM_SCROLL_LINES_PER_KB = 2;
/**
 * Полоса гистерезиса вокруг порога (аудит 13.09, A02). На одном и том же
 * размере 16 КиБ 31 строка давала `application`, 32 — `terminal`: одна строка
 * вывода переключала источник между двумя свайпами. Однажды вынесенный вердикт
 * меняется, только когда поток уверенно ушёл за полосу.
 */
export const STREAM_HYSTERESIS_LINES_PER_KB = 0.5;
/** Меньше такого объёма вывода вердикт по потоку не выносим — шума больше, чем сигнала. */
export const STREAM_SAMPLE_MIN_BYTES = 4096;
/**
 * Окно замера. Счётчики не копятся вечно: набрав столько байт, оба делятся
 * пополам, и недавнее поведение перевешивает давнее.
 *
 * ⚠ Без затухания замер врал бы РОВНО В ГЛАВНОМ случае: терминал, где оболочка
 * напечатала сотни строк, а потом запустили Claude. Реплей кольца при открытии
 * приносит те старые строки как обычный поток, и сессия навсегда осталась бы
 * «прокручиваемой» — то есть у Claude снова отобрали бы PgUp, ровно тот дефект,
 * который чинили 2.57.9. 16 КБ выбраны как половина замерного окна 32 КБ, на
 * котором получены боевые числа агентов.
 */
export const STREAM_WINDOW_BYTES = 16 * 1024;

/** Затухание замера: старое поведение приложения не должно решать за новое. */
export function decayStreamSample(lines: number, bytes: number): { lines: number; bytes: number } {
  if (bytes <= STREAM_WINDOW_BYTES) return { lines, bytes };
  return { lines: Math.round(lines / 2), bytes: Math.round(bytes / 2) };
}

/**
 * Что показал замер потока текущего приложения: `lines` — сколько строк ушло в
 * scrollback, `bytes` — сколько байт вывода при этом пришло. Оба счётчика
 * обнуляются при смене переднего процесса: вердикт принадлежит приложению, а не
 * терминалу.
 */
export function historyOwnerFromStream(lines: number, bytes: number): HistoryOwner {
  if (!(bytes >= STREAM_SAMPLE_MIN_BYTES)) return "unknown";
  return (lines * 1024) / bytes >= STREAM_SCROLL_LINES_PER_KB ? "terminal" : "application";
}

/**
 * Тот же замер, но с памятью прежнего вердикта: у порога есть полоса, внутри
 * которой вердикт не меняется (A02, T-04). Без прежнего вердикта — обычный порог.
 */
export function historyOwnerFromStreamStable(prev: HistoryOwner, lines: number, bytes: number): HistoryOwner {
  if (!(bytes >= STREAM_SAMPLE_MIN_BYTES)) return "unknown";
  const rate = (lines * 1024) / bytes;
  if (prev === "terminal") {
    return rate >= STREAM_SCROLL_LINES_PER_KB - STREAM_HYSTERESIS_LINES_PER_KB ? "terminal" : "application";
  }
  if (prev === "application") {
    return rate >= STREAM_SCROLL_LINES_PER_KB + STREAM_HYSTERESIS_LINES_PER_KB ? "terminal" : "application";
  }
  return rate >= STREAM_SCROLL_LINES_PER_KB ? "terminal" : "application";
}

/**
 * Кому принадлежит история прокрутки по слабой эвристике. Решает только в
 * отсутствие объявления и наблюдения (navigationDecision.ts).
 */
export function resolveHistoryOwner(s: {
  /** Вердикт замера потока (см. historyOwnerFromStream). */
  stream: HistoryOwner;
  /** Глубина СВОЕЙ прокрутки терминала (baseY нормального буфера). */
  ownScrollback: number;
  /** На переднем плане AI-агент. */
  agent: boolean;
  /** Приложение рисует в альтернативном экране. */
  alt: boolean;
}): HistoryOwner {
  // У alt-screen нет scrollback ни в одном эмуляторе мира — это свойство
  // протокола, а не наша недоработка. Историю, если она есть, держит приложение.
  if (s.alt) return "application";
  if (s.stream === "terminal") return "terminal";
  if (s.stream === "application") return s.agent ? "application" : "terminal";
  // Замера ещё нет: приложение не напечатало ни килобайта с тех пор, как встало
  // на передний план. Тогда решает глубина — это поведение 2.57.12, проверенное
  // живьём, и оно остаётся страховкой, а не главным правилом.
  if (s.ownScrollback >= OWN_HISTORY_LINES) return "terminal";
  return s.agent ? "application" : "terminal";
}

/** Канал, которым листаем. */
export type AltScrollChannel = "viewport" | "wheel" | "page" | "arrows" | "none";

const ESC = "\x1b";

/**
 * Отчёт колеса в SGR-кодировке (1006), склеенный по числу строк.
 * Кнопка 64 — вверх, 65 — вниз; координата берётся в центре вьюпорта: для
 * прокрутки позиция курсора приложению безразлична.
 */
export function wheelSeq(lines: number, cols: number, rows: number): string {
  const n = Math.abs(lines);
  if (n === 0) return "";
  const btn = lines < 0 ? 64 : 65;
  const col = Math.max(1, Math.min(cols, Math.round(cols / 2)));
  const row = Math.max(1, Math.min(rows, Math.round(rows / 2)));
  return `${ESC}[<${btn};${col};${row}M`.repeat(n);
}

/**
 * PgUp/PgDn, пересчитанные из строк в страницы. Меньше одной страницы не
 * шлём: у страничного канала нет дробного шага, и «пол-экрана» превратилось бы
 * в ноль — человек тянул бы палец без всякого эффекта.
 */
export function pageSeq(lines: number, rows: number): string {
  const n = Math.abs(lines);
  if (n === 0) return "";
  const perPage = Math.max(1, rows - 1); // как у настоящего PgUp: строка нахлёста
  const pages = Math.max(1, Math.round(n / perPage));
  return (lines < 0 ? `${ESC}[5~` : `${ESC}[6~`).repeat(pages);
}

/**
 * Сколько ЦЕЛЫХ страниц набралось и что осталось в остатке.
 *
 * ⚠ Без этого один спокойный свайп улетал на десяток экранов. Накопитель
 * прокрутки обнуляется КАЖДЫЙ кадр анимации, а медленный drag на Android даёт
 * по одной строке в кадре — и `pageSeq` честно отправлял минимум одну страницу
 * на каждый такой кадр: тридцать кадров = тридцать `PgUp` (внешний разбор
 * 2.57.9, T259-03). Поэтому для страничного канала накопитель живёт МЕЖДУ
 * кадрами: страница уходит, только когда набралось на полэкрана, остаток
 * переносится дальше.
 *
 * Потолок на один заход — три страницы: быстрый flick должен листать бодро, но
 * не уносить человека на десять экранов, откуда он не найдёт дорогу назад.
 */
export function pagesFromAccum(
  accum: number,
  rows: number,
  budget = MAX_PAGES_PER_GESTURE,
): { pages: number; rest: number } {
  const step = Math.max(1, Math.floor(Math.max(2, rows) / 2));
  const sign = accum < 0 ? -1 : 1;
  const left = Math.max(0, Math.min(MAX_PAGES_PER_GESTURE, budget));
  // Бюджет жеста исчерпан — накопленное не «подождёт до следующего кадра», а
  // выбрасывается: иначе остаток выстрелит страницами уже после того, как палец
  // остановился (см. MAX_PAGES_PER_GESTURE).
  if (left === 0) return { pages: 0, rest: 0 };
  const whole = Math.floor(Math.abs(accum) / step);
  if (whole === 0) return { pages: 0, rest: accum };
  const pages = Math.min(left, whole);
  return { pages: pages * sign, rest: accum - pages * step * sign };
}

/**
 * Потолок страниц на ОДИН жест пальца, а не на один кадр анимации.
 *
 * ⚠ 2.57.12 объявляла потолок три, но считала его на каждый вызов: остаток
 * переносился между кадрами, инерция вызывала спуск десятки раз, и жест уносил
 * человека куда угодно. Замеры повторного аудита на нашей же модели инерции
 * (`velocity *= 0.94` каждые 16 мс): начальная скорость 4 px/мс → 4 страницы,
 * 8 px/мс → 8 страниц, а искусственная тысяча накопленных строк → 66 страниц
 * при «потолке 3».
 *
 * Поэтому бюджет живёт у ЖЕСТА: обнуляется на касании, тратится отправками и не
 * пополняется инерцией — докрутка по инерции осмысленна для своего вьюпорта
 * (пиксели), но не для страничного канала, где шаг дискретный.
 */
export const MAX_PAGES_PER_GESTURE = 3;

/** Через сколько миллисекунд в запас возвращается одна страница. */
export const PAGE_REFILL_MS = 250;

/**
 * Пополнение запаса страниц со временем.
 *
 * ⚠ ПОЧЕМУ ПОТОЛОК СТАЛ ПРО СКОРОСТЬ, А НЕ ПРО ДЛИНУ ЖЕСТА. Жёсткие «три
 * страницы на жест» (2.57.13) закрыли улёт от инерции, но принесли свою жалобу:
 * «и дальше не скролит» (14.08.2026). Человек тянет палец не отрывая — а
 * прокрутка встаёт после третьей страницы и ждёт, пока он оторвёт палец и
 * начнёт заново. Проверено на его телефоне: длинный свайп листает и
 * останавливается.
 *
 * Защита нужна от БЫСТРОГО броска (десять экранов за флик), а не от долгого
 * осознанного движения. Поэтому запас в три страницы восстанавливается сам:
 * четыре страницы в секунду — быстрее, чем человек успевает читать, и заметно
 * медленнее, чем улетает инерция.
 */
export function refillPageBudget(budget: number, elapsedMs: number): number {
  return refillPageBudgetAt(budget, elapsedMs).budget;
}

/**
 * То же пополнение, но честно сообщает, СКОЛЬКО времени оно израсходовало.
 *
 * ⚠ ВНЕШНИЙ АУДИТ 2.57.18 (14.08.2026), находка P0-01: вызывающий сдвигал
 * свою временную метку на «сейчас» при КАЖДОМ кадре жеста, а пополнение
 * срабатывает раз в 250 мс. На кадрах по 16 мс `floor(16/250) = 0` — и остаток
 * (234 мс) выбрасывался вместе со старой меткой. Следующий кадр начинал с нуля,
 * и долгий свайп вставал после исходных трёх страниц навсегда — ровно та
 * жалоба «и дальше не скролит», которую пополнение и должно было закрыть.
 *
 * Поэтому метку разрешается двигать только на ИЗРАСХОДОВАННОЕ время:
 *
 *   const r = refillPageBudgetAt(budget, nowMs - budgetAt);
 *   budget = r.budget;
 *   budgetAt += r.consumedMs; // недобранные до 250 мс остаются в запасе
 */
export function refillPageBudgetAt(
  budget: number,
  elapsedMs: number,
): { budget: number; consumedMs: number } {
  if (!(elapsedMs > 0)) return { budget, consumedMs: 0 };
  const gained = Math.floor(elapsedMs / PAGE_REFILL_MS);
  if (gained <= 0) return { budget, consumedMs: 0 };
  return {
    budget: Math.min(MAX_PAGES_PER_GESTURE, budget + gained),
    consumedMs: gained * PAGE_REFILL_MS,
  };
}

/** Стрелки для пейджеров (less/man). Агенту НЕ отправляются — см. шапку. */
export function arrowSeq(lines: number): string {
  const n = Math.abs(lines);
  if (n === 0) return "";
  return (lines < 0 ? `${ESC}[A` : `${ESC}[B`).repeat(n);
}

/**
 * Края разговора для кнопок ⇈/⇊: Ctrl+Home и Ctrl+End. У агента это
 * документированный переход в начало и конец вывода — честнее, чем «очень
 * много страниц подряд», и стоит два байта вместо сотни сообщений.
 */
export function edgeSeq(up: boolean): string {
  return up ? `${ESC}[1;5H` : `${ESC}[1;5F`;
}

/**
 * Отчёт о КЛИКЕ мышью в SGR-кодировке (1006): нажатие левой кнопки и
 * отпускание в той же ячейке.
 *
 * Зачем это на телефоне. Полноэкранные приложения рисуют кликабельные вещи:
 * у Claude Code это плашка «N new messages (ctrl+End)», пункты меню
 * разрешений, свёрнутый вывод команды. За компьютером их нажимают мышью, а с
 * телефона было нечем — мы слали только колесо. Человек видел кнопку и не мог
 * её нажать.
 *
 * `col`/`row` — 1-based координаты ячейки под пальцем.
 */
export function clickSeq(col: number, row: number, cols: number, rows: number): string {
  const c = Math.max(1, Math.min(cols, Math.round(col)));
  const r = Math.max(1, Math.min(rows, Math.round(row)));
  return `${ESC}[<0;${c};${r}M${ESC}[<0;${c};${r}m`;
}

/**
 * Что отправить приложению выбранным каналом на `lines` строк (отрицательное —
 * вверх, к старому выводу). Пустая строка — слать нечего: либо своя история,
 * либо честное объяснение человеку.
 *
 * `edge` — нажата кнопка «в самое начало/конец» (⇈/⇊), а не жест пальцем.
 */
export function channelPayload(
  channel: AltScrollChannel,
  lines: number,
  cols: number,
  rows: number,
  edge = false,
): string {
  switch (channel) {
    case "wheel":
      return wheelSeq(lines, cols, rows);
    case "page":
      return edge ? edgeSeq(lines < 0) : pageSeq(lines, rows);
    case "arrows":
      return arrowSeq(lines);
    default:
      return "";
  }
}
