/**
 * Когда к кадру экрана применять присланную сервером историю scrollback
 * (SOTA-снапшот: replay полной заменой, модель VS Code).
 *
 * Кадр `{t:"screen"}` с необязательным полем `history` приходит ВНУТРИ
 * соединения, и что с ним делать, решает sync-маркер этого же соединения:
 *
 *   reset   → терминал свежий (RIS уже исполнен на маркере): своей истории
 *             нет. Присланную печатаем ПЕРЕД кадром: строки последовательно
 *             уходят в scrollback, абсолютно адресованный кадр ложится поверх.
 *   resumed → сервер дослал только хвост, СВОЯ история валидна: чужая
 *             продублировала бы её — игнорируем, кадр применяем как есть.
 *
 * Два края, ради которых правило — отдельный конечный автомат, а не проверка
 * «был ли reset» на коленке:
 *
 *   1. Кадр без маркера. requestScreenFrame зовётся и при возврате из фона
 *      (queueGap) — маркера в этом соединении не было, терминал НЕ пуст, и
 *      применить историю там значит стереть живой вывод посреди работы.
 *   2. Один раз за соединение. Кадров в соединении может быть несколько
 *      (onopen, потом возврат из фона): история применяется на первом кадре
 *      С историей после reset, дальше готовность снята — иначе каждый
 *      повторный кадр переписывал бы scrollback заново.
 *
 * Кадр БЕЗ поля history готовность не тратит: зеркало могло быть неживым
 * ровно в момент первого кадра, и следующий (с историей) остаётся
 * единственным шансом восстановить scrollback этого соединения.
 *
 * Чистое правило: ни xterm, ни DOM, ни сети — проверяется тестом без React
 * (общий приём проекта, см. tapGuard/altScroll).
 */

/** Состояние на соединение: none — применять нельзя; ready — был reset, история
 * ещё не применялась; done — уже применяли в этом соединении. */
export type SnapshotHistory = "none" | "ready" | "done";

/** Новое соединение: маркера ещё не было, история запрещена. */
export const SNAPSHOT_HISTORY_INIT: SnapshotHistory = "none";

/**
 * Sync-маркер соединения. reset разрешает применение ВСЕГДА — в том числе
 * после "done": повторный reset в том же соединении означает новую эпоху
 * потока (сервер пересоздал сессию), терминал снова стёрт RIS'ом и снова
 * пуст. resumed запрещает: своя история валидна.
 *
 * `termVirgin` — терминал ЭТОЙ СТРАНИЦЫ ещё не печатал ни байта вывода.
 * Тогда resumed тоже разрешает: с 2.55.19 позиция потока переживает страницу
 * (resumeStore в localStorage), и СВЕЖАЯ страница приходит с resume= — сервер
 * отвечает resumed и досылает только хвост. «Своя история валидна» здесь ложь:
 * история осталась в памяти ЗАКРЫТОЙ страницы, у новой xterm пуст. Боевой
 * скриншот 13.08.2026 («вот тут не скролит», сессия «Отчет»): экран собран
 * кадром, а прокручивать нечего — scrollback ноль строк, снапшот с историей
 * был отброшен ровно этим правилом.
 */
export function noteSyncMarker(
  marker: "reset" | "resumed",
  termVirgin = false,
): SnapshotHistory {
  if (marker === "reset") return "ready";
  return termVirgin ? "ready" : "none";
}

/**
 * Решение для пришедшего кадра экрана. `hasHistory` — есть ли в кадре
 * непустое поле history: кадр без него готовность не расходует (см. шапку).
 */
export function takeSnapshotHistory(
  s: SnapshotHistory,
  hasHistory: boolean,
): { apply: boolean; next: SnapshotHistory } {
  if (s !== "ready") return { apply: false, next: s };
  if (!hasHistory) return { apply: false, next: s };
  return { apply: true, next: "done" };
}
