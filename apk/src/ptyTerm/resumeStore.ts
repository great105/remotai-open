// Позиция в потоке вывода терминала, пережившая закрытие приложения.
//
// Зачем понадобилось. `epoch` и `offset` жили только в `useRef` экрана
// (PtyTermView), то есть в памяти компонента. Этого хватало на реконнект при
// ОТКРЫТОМ экране — ради чего механизм и делали 02.08.2026, — но компонент
// умирает, когда человек уходит с экрана или закрывает приложение. Дальше
// открытие начиналось с нуля: `resumeParam` получал пустую эпоху, запрос уходил
// без `?resume=`, и агент отдавал весь хвост кольца.
//
// Цена этого замерена на релее 11.08.2026 по жалобе «открываю терминал, жду
// секунд 20, пока появится текст»: 0,5–0,9 МБ вниз на КАЖДОЕ открытие (медиана
// ~580 КБ) при 250–1700 байтах вверх, и 466 из 677 открытий за сутки (68 %)
// приходили без resume. Сценарий владельца — «посмотрел, дал запрос, закрыл
// приложение, открыл снова» — попадал мимо оптимизации целиком.
//
// Ошибиться здесь можно только в безопасную сторону: что бы отсюда ни пришло,
// решение принимает агент (`snapshotTail`, internal/pty/host_common.go).
// Позиция свежая — дошлёт точный хвост; протухла и вытеснена из кольца —
// ограниченный хвост вместо лавины; чужая эпоха, ноль или мусор — полный
// снапшот, то есть ровно прежнее поведение.

/**
 * Позиция: «поток этой эпохи у меня есть до этого байта».
 *
 * `hist` — сколько строк ПРОКРУТКИ отдало зеркало экрана в прошлый раз. Хранится
 * рядом с позицией, потому что решается им один вопрос: можно ли новой странице
 * начинать с resume (см. shouldUseColdResume).
 */
export type ResumePos = { epoch: string; offset: number; hist?: number };

/**
 * Начиная с какой глубины история зеркала считается заменой полному реплею.
 *
 * Ниже этого — снапшот даёт человеку меньше трёх экранов сверх видимого, то есть
 * практически ничего, и ради прокрутки выгоднее заплатить реплеем.
 */
export const RICH_HISTORY_LINES = 100;

/**
 * Можно ли НОВОЙ странице начинать с сохранённого resume.
 *
 * Resume хранит только позицию байтового потока. Сам буфер xterm вместе со
 * scrollback умирает вместе со страницей, и сервер, получив resume, честно
 * досылает лишь дельту — у простаивающего агента она пустая. Значит вся
 * прокрутка новой страницы обязана прийти из ИСТОРИИ ЗЕРКАЛА. Если зеркало
 * бедное, её взять неоткуда, и человек получает один экран.
 *
 * Живой замер 13.08.2026 (лог агента владельца, диагностика what=snapshot):
 *
 *   сессия 7285b79b: зеркало=4   своя=0 → взяли 4 строки, листать нечего;
 *   сессия 10b8b057: зеркало=500 своя=0 → взяли 500, всё в порядке;
 *   сессия 8bbc31fb: зеркало=500 своя=0 → 500.
 *
 * ⚠ Обе первые — Claude Code. Поэтому решать ПО ВИДУ АГЕНТА нельзя: у одной его
 * сессии зеркало пустое, у другой полное. Отличает их не имя агента, а то,
 * уходят ли строки вверх (зеркало копит) или экран перерисовывается на месте
 * (копить нечего). Единственный честный признак — сама глубина, и она у нас
 * уже измерена прошлым снапшотом. Плюс это правило проекта: клиент не
 * хардкодит поведение конкретных агентов.
 *
 * Неизвестная глубина (первое открытие, старый агент, запись прошлых версий) —
 * реплей: один лишний хвост дешевле необратимо пустой прокрутки. После первого
 * же снапшота глубина запоминается, и дальше решение точное.
 */
export function shouldUseColdResume(pos: ResumePos | null): boolean {
  if (!pos) return false;
  if (typeof pos.hist !== "number") return false;
  return pos.hist >= RICH_HISTORY_LINES;
}

/**
 * Стоит ли ТЁПЛОМУ переподключению попросить один кадр только ради глубины
 * истории зеркала (причина hist-probe координатора).
 *
 * Глубина `hist` обновляется только кадром экрана, а тёплое переподключение
 * кадр не просит (ST-09 A6). Страница, открытая при бедном зеркале и дальше
 * жившая на тёплых переподключениях, навсегда оставляла в хранилище hist < 100,
 * хотя зеркало давно разбогатело: следующее холодное открытие шло без resume, и
 * агент отдавал весь хвост кольца (до 512 КиБ) вместо десятков байт — ровно
 * сценарий «дал запрос, закрыл, открыл» (инцидент 11.08). Живьём на агенте
 * 2.71.1 (ревью 15.09): 15 КБ реплея против 58 Б resumed.
 *
 * Просим, только если сохранённое решение сейчас «реплей» (то же правило, что
 * shouldUseColdResume: глубина ниже RICH_HISTORY_LINES или неизвестна, `hist`
 * отрицательный или не число) И с прошлого кадра поток ушёл в прокрутку
 * (`linesSinceFrame` > 0): без новых строк зеркалу копить нечего, ответ был бы
 * тем же числом. Богатое зеркало — не просим вовсе.
 */
export function shouldProbeHistory(hist: number, linesSinceFrame: number): boolean {
  if (!(linesSinceFrame > 0)) return false;
  const known = Number.isSafeInteger(hist) && hist >= 0;
  return !(known && hist >= RICH_HISTORY_LINES);
}

/** Ключ рядом с `pty.draft.<id>`, который уже живёт в этом же хранилище. */
function key(id: string): string {
  return `pty.resume.${id}`;
}

/**
 * Прочитать сохранённую позицию сессии. Отсутствие, мусор и любой отказ
 * хранилища — это `null`, то есть «начинаем с нуля», а не исключение: сломанный
 * localStorage не имеет права мешать открыть терминал.
 */
export function loadResumePos(id: string): ResumePos | null {
  if (!id) return null;
  try {
    const raw = localStorage.getItem(key(id));
    if (!raw) return null;
    const parsed = JSON.parse(raw);
    const epoch = parsed?.epoch;
    const offset = parsed?.offset;
    // Эпоха обязана быть непустой строкой: пустая означает «просить нечего», и
    // resumeParam всё равно вернул бы undefined.
    if (typeof epoch !== "string" || !epoch) return null;
    // Смещение — конечное неотрицательное целое. Дробное/NaN/Infinity/минус
    // склеились бы в параметр вида `ep:NaN`, который агенту разбирать нечем.
    if (typeof offset !== "number" || !Number.isSafeInteger(offset) || offset < 0) return null;
    // Глубина истории — необязательная: записи прошлых версий её не знают, и это
    // законное «неизвестно», а не повод выбросить всю позицию.
    const hist = parsed?.hist;
    const ok = typeof hist === "number" && Number.isSafeInteger(hist) && hist >= 0;
    return ok ? { epoch, offset, hist } : { epoch, offset };
  } catch {
    return null;
  }
}

/**
 * Запомнить позицию. Пустая эпоха стирает запись: она означает, что потока этой
 * сессии у нас нет, и хранить прежнее значение опаснее, чем не хранить ничего.
 */
export function saveResumePos(id: string, pos: ResumePos): void {
  if (!id) return;
  if (!pos.epoch || !Number.isSafeInteger(pos.offset) || pos.offset < 0) {
    clearResumePos(id);
    return;
  }
  try {
    const rec: Record<string, unknown> = { epoch: pos.epoch, offset: pos.offset };
    if (typeof pos.hist === "number" && pos.hist >= 0) rec.hist = pos.hist;
    localStorage.setItem(key(id), JSON.stringify(rec));
  } catch {
    // Переполненное или запрещённое хранилище — просто работаем как раньше.
  }
}

/** Забыть позицию (процесс завершился — продолжать нечего). */
export function clearResumePos(id: string): void {
  if (!id) return;
  try {
    localStorage.removeItem(key(id));
  } catch {
    /* хранилище недоступно — забывать всё равно нечего */
  }
}
