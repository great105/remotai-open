/**
 * ДВЕ ГЕОМЕТРИИ ТЕРМИНАЛА, КОТОРЫЕ НЕЛЬЗЯ ПУТАТЬ.
 *
 *   логическая  — размер терминала и PTY (например 48×30). Ею адресуются все
 *                 команды агента: «поставить курсор на строку 22», «нарисовать
 *                 статус на строке 30». Клавиатура её НЕ меняет.
 *   видимая     — сколько строк человек видит прямо сейчас. С поднятой
 *                 клавиатурой это 9–11 строк, а верх уходит за край коробки.
 *
 * ⚠ ЖИВОЙ ДЕФЕКТ (боевой лог 13.08.2026, 24 снимка из 200): клиент ужимал
 * ЛОГИЧЕСКУЮ геометрию до видимой. `fit()` при открытии соединения считал
 * 48×10, отправка размера при клавиатуре молчала (и правильно делала), PTY
 * оставался 48×30 — и кадр в тридцать строк писался в десятистрочный терминал.
 * Команды перехода на строки 11–30 зажимались последней доступной строкой, и
 * всё сваливалось в самый низ. Строки лога: `снапшот=48x31 клиент=48x11`.
 *
 * ⚠ И ОБРАТНОЕ РЕШЕНИЕ ТОЖЕ НЕВЕРНО: уменьшить PTY под клавиатуру нельзя.
 * Тогда Claude и Codex перерисуют весь TUI, зритель за компьютером получит
 * девятистрочный терминал, а при закрытии клавиатуры всё повторится обратно.
 * Клавиатура обязана обрезать и сдвигать ВИДИМОЕ окно, не трогая логическое.
 */

/** Что делать с пришедшим кадром экрана. */
export type FrameGeometryAction =
  /** Геометрия совпала (или её не с чем сравнить) — писать кадр как есть. */
  | { kind: "apply" }
  /**
   * Высота кадра разошлась с нашей при ПОДНЯТОЙ клавиатуре: логическую высоту
   * надо привести к кадру ЛОКАЛЬНО (term.resize), НЕ отправляя размер на
   * компьютер, и только потом писать кадр. Кадр выше — вернуть себе строки,
   * которые схлопывались бы в последнюю; кадр ниже — ужаться, иначе низ
   * логического терминала пуст, а просьба о свежем кадре под клавиатурой
   * сойтись не может (размер туда не уходит). Видимое окно останется прежним —
   * его двигает peek.
   */
  | { kind: "restore"; cols: number; rows: number }
  /**
   * Кадр снят в АВТОРИТЕТНОЙ ширине PTY (`state.cols`), а наш терминал шире:
   * рядом открыт более узкий зритель, и сервер держит PTY по минимуму. Просить
   * свежий кадр бессмысленно — он придёт в той же ширине, и «отверг → попроси»
   * крутился бы вечно (внешний аудит 2.57.18, находка P0-05: при двух зрителях
   * 48×30 и 232×40 широкий не принимал НИ ОДНОГО кадра). Поэтому логическую
   * сетку принимаем себе ЛОКАЛЬНО (term.resize), как уже делает высота, и
   * пишем кадр. Серверу продолжаем сообщать СВОЮ измеренную ширину — иначе при
   * уходе узкого зрителя PTY некуда было бы расти.
   */
  | { kind: "adopt"; cols: number; rows: number }
  /**
   * Расхождение не клавиатурное: наш размер честный, а кадр снят в чужой
   * геометрии. Шлём свой размер и просим свежий.
   *
   * `apply` — писать ли этот кадр, пока свежий не пришёл:
   *   • разошлась ВЫСОТА — да. Строки адресованы абсолютно, лишние просто не
   *     заполнятся; пустой экран хуже неполного.
   *   • разошлась ШИРИНА — НЕТ. Перенос длинных строк и вся сетка кадра
   *     посчитаны под другую ширину, и написать его — значит своими руками
   *     сделать кашу (боевая строка 14.08.2026: `снапшот=48x30
   *     логический=232x40`, кадр применялся). Экран при этом не пустеет: у нас
   *     есть живой поток, а свежий кадр придёт следом.
   */
  | { kind: "resync"; apply: boolean };

export function frameGeometryAction(s: {
  /** Геометрия кадра, как её объявил компьютер (может отсутствовать у старого агента). */
  snapCols?: number;
  snapRows?: number;
  /** Логическая геометрия нашего терминала прямо сейчас. */
  termCols: number;
  termRows: number;
  /** Экранная клавиатура поднята. */
  keyboardOpen: boolean;
  /**
   * Авторитетная ширина PTY из /state (0/не задана — ещё не знаем). Ей кадр
   * разрешается принять чужую на вид ширину: кадр снят РОВНО в ней.
   */
  authoritativeCols?: number;
  authoritativeRows?: number;
  /**
   * Кадр пришёл на запрос, отправленный ПОСЛЕ доставки нашей вместимости в
   * этот же сокет (`capacityDelivered` из resizePolicy). По умолчанию false —
   * прежнее поведение.
   */
  capacityDelivered?: boolean;
}): FrameGeometryAction {
  const { snapCols, snapRows, termCols, termRows, keyboardOpen, authoritativeCols } = s;
  if (!isSize(snapCols) || !isSize(snapRows)) return { kind: "apply" };
  // ⚠ КАДР ПОСЛЕ ДОСТАВЛЕННОЙ ВМЕСТИМОСТИ — ЭТО СЕТКА PTY, ПО ОБЕИМ ОСЯМ (ST-08,
  // T-32). Сервер читает resize и screen одной горутиной по порядку
  // (api_pty.go:1377-1548), кадр ждёт окончания смены геометрии
  // (session_screen.go:829-839): кадр на такой запрос снят в min(всех зрителей,
  // включая нас). Считать его «возможно чужим» и просить снова — это и был
  // вечный круг «кадр → resync → запрос» у двух зрителей разной высоты в
  // скрытой вкладке, где нет опроса /state (журнал 2026-09-03, п. 4).
  // Принимаем сетку локально; серверу по-прежнему уходит наша вместимость
  // (I-10), поэтому при уходе меньшего зрителя PTY есть куда расти.
  // Под клавиатурой правило не действует: там своя правда — restore ниже.
  if (s.capacityDelivered && !keyboardOpen && (snapCols !== termCols || snapRows !== termRows)) {
    return { kind: "adopt", cols: snapCols, rows: snapRows };
  }
  // ⚠ ШИРИНУ ПОДОГНАТЬ НЕЛЬЗЯ, И ПИСАТЬ ТАКОЙ КАДР ТОЖЕ НЕЛЬЗЯ — кроме одного
  // случая: кадр снят в авторитетной ширине самого PTY. Тогда чужая она только
  // на вид (наш экран шире общего терминала), и правильный приём — принять
  // авторитетную сетку себе, а не воевать с ней бесконечными resync'ами.
  if (snapCols !== termCols) {
    if (isSize(authoritativeCols) && snapCols === authoritativeCols) {
      return { kind: "adopt", cols: snapCols, rows: snapRows };
    }
    return { kind: "resync", apply: false };
  }
  if (snapRows === termRows) return { kind: "apply" };
  // Same width does not imply the same PTY grid: a shorter second viewer
  // controls height too. A current frame in the known grid converges locally.
  if (snapCols === authoritativeCols && snapRows === s.authoritativeRows) {
    return { kind: "adopt", cols: snapCols, rows: snapRows };
  }
  // При поднятой клавиатуре высота кадра — единственная правда, В ОБЕ СТОРОНЫ.
  // Размер на компьютер под клавиатурой не уходит (и правильно), поэтому
  // «попросить свежий кадр» сойтись не может по построению: кадр придёт в той
  // же высоте, и круг «кадр → запрос кадра» крутится раз в секунду, пока
  // клавиатура не закроется. Боевой лог 06.09.2026 (id=0db7db7e97b04f6c):
  // коробка выросла на 4 строки (ушёл блок «Запустить ИИ-агента»), уточнённый
  // размер не успел уйти, человек начал печатать — 12 секунд `снапшот=48x24
  // логический=48x28 клавиатура=true решение=resync`, кадр за кадром. Живое
  // воспроизведение — build/qa/ia/live-term-keyboard.mjs (GROW=1).
  //   • кадр ВЫШЕ — те самые строки, которые схлопывались в последнюю: наша
  //     ошибка измерения, логическую высоту возвращаем себе;
  //   • кадр НИЖЕ — коробка подросла, а PTY остался прежним: логическую
  //     высоту ужимаем до кадра, иначе видимое окно (низ логического
  //     терминала) показывает пустые строки под курсором.
  // Компьютеру по-прежнему уходит измеренная высота (reportSizeRef) — когда
  // клавиатура уйдёт, refit пришлёт честный размер обычным путём.
  if (keyboardOpen) return { kind: "restore", cols: termCols, rows: snapRows };
  // Клавиатуры нет — наш размер честный, а компьютер его ещё не знает (или
  // PTY идёт по другому зрителю). Кадр ВЫШЕ: строки за краем зажимаются
  // последней, пишем и просим свежий. Кадр НИЖЕ: лишние строки просто
  // останутся пустыми после его же стирания экрана — картинку не ломает.
  return { kind: "resync", apply: true };
}

/**
 * Какую логическую высоту держать при поднятой клавиатуре.
 *
 * `fit()` честно считает, сколько строк помещается в коробку, и при клавиатуре
 * это 9–11. Берём вместо неё последнюю известную логическую высоту — из
 * состояния сессии (`/state` отдаёт применённый к PTY размер) или из последнего
 * кадра. Ничего не знаем — остаёмся на измеренной: врать в другую сторону хуже.
 */
export function logicalRowsForKeyboard(measuredRows: number, knownRows: number): number {
  if (!isSize(knownRows)) return measuredRows;
  return knownRows > measuredRows ? knownRows : measuredRows;
}

function isSize(v: number | undefined): v is number {
  return typeof v === "number" && Number.isFinite(v) && v >= 2;
}

/**
 * ПОЧЕМУ ИЗМЕНИЛАСЬ КОРОБКА ТЕРМИНАЛА: ПЕРЕКРЫТИЕ ИЛИ ВМЕСТИМОСТЬ (ST-08, T-31).
 *
 * Плашки `.pty-agent-ask` и `.pty-upload-strip` лежат в той же flex-колонке,
 * что и терминал, и их появление сжимает коробку. ResizeObserver видел «окно
 * не менялось» и шёл в fitLocal + sendResize: через 2 с отстоя PTY получал
 * resize, TUI перерисовывал всю переписку, а скрытие плашки повторяло всё
 * обратно (карта ST-08, gap T-31). Плашка — это временное ЛОКАЛЬНОЕ
 * перекрытие, как клавиатура (I-09): видимое окно сдвигается peek'ом, а
 * вместимость устройства прежняя.
 *
 * Знаки: `boxDeltaPx` — новая высота коробки минус прежняя; `occluderDeltaPx`
 * — новая суммарная высота плашек минус прежняя. Плашка выросла на 40 px —
 * коробка сжалась на 40 px: сумма ноль, это перекрытие.
 *
 * Всё остальное — вместимость, то есть прежний путь:
 *   • изменилось окно или ширина — это поворот, другое окно, панель браузера;
 *   • плашки не менялись — объяснять изменение коробки нечем;
 *   • изменение коробки объясняется плашкой лишь частично (разница больше
 *     допуска на дробные пиксели) — значит, вместе с ней поменялось что-то
 *     ещё, и промолчать о настоящем изменении хуже лишнего resize.
 */
export type LayoutChange = "occlusion" | "capacity";

/** Допуск на дробные пиксели вёрстки (devicePixelRatio, округление flex). */
export const OCCLUSION_TOLERANCE_PX = 2;

export function layoutChange(s: {
  windowChanged: boolean;
  widthChanged: boolean;
  boxDeltaPx: number;
  occluderDeltaPx: number;
}): LayoutChange {
  if (s.windowChanged || s.widthChanged) return "capacity";
  if (!Number.isFinite(s.boxDeltaPx) || !Number.isFinite(s.occluderDeltaPx)) return "capacity";
  if (Math.abs(s.occluderDeltaPx) <= OCCLUSION_TOLERANCE_PX) return "capacity";
  return Math.abs(s.boxDeltaPx + s.occluderDeltaPx) <= OCCLUSION_TOLERANCE_PX ? "occlusion" : "capacity";
}

/**
 * ВМЕСТИМОСТЬ ПО ВЫСОТЕ, ПОКА КОРОБКУ ПЕРЕКРЫВАЕТ ПЛАШКА (T-31).
 *
 * `measuredRows` — сколько строк fit насчитал в сжатой коробке; плашка
 * занимает `occluderPx`. Вместимость — сколько строк поместилось бы без неё.
 *
 * ⚠ Округляем ВНИЗ, а не к ближайшему: переоценка на одну строку делает PTY
 * выше коробки без плашки, и нижняя строка (обычно строка ввода) навсегда
 * уходит под край — это ровно срез низа из жалобы 04.08. Недооценка на строку
 * даёт в худшем случае пустую строку снизу. Если известна высота самой
 * коробки (`boxPx`), считаем точно так же, как fit: floor((коробка + плашка) /
 * ячейка).
 */
export function capacityWithOccluder(measuredRows: number, occluderPx: number, cellPx: number, boxPx?: number): number {
  if (!isSize(measuredRows)) return measuredRows;
  if (!Number.isFinite(occluderPx) || occluderPx <= 0 || !Number.isFinite(cellPx) || cellPx <= 0) return measuredRows;
  if (typeof boxPx === "number" && Number.isFinite(boxPx) && boxPx > 0) {
    return Math.max(measuredRows, Math.floor((boxPx + occluderPx) / cellPx + 1e-6));
  }
  return measuredRows + Math.floor(occluderPx / cellPx + 1e-6);
}

/**
 * ЧТО СЧИТАЕТСЯ ВРЕМЕННЫМ ПЕРЕКРЫТИЕМ КОРОБКИ ТЕРМИНАЛА (ST-08, T-31).
 *
 * Плашки, которые приходят и уходят САМИ, по состоянию процесса или связи, и
 * сжимают коробку, лёжа с ней в одной flex-колонке `.pty-page`. Их высота — не
 * вместимость устройства: пока они на экране, видимое окно сдвигается к
 * курсору, а PTY остаётся прежним (I-09). Каждая полоса колонки решена явно:
 *   • `.pty-agent-ask` — вопрос агента, живёт до ответа;
 *   • `.pty-upload-strip` — загрузка файла, живёт секунды;
 *   • `.pty-width-notice` — уведомление о суженном общем выводе, уходит с
 *     уходом узкого зрителя;
 *   • `.pty-update-bar` — «компьютер обновляется», снимается восстановленной
 *     связью через секунды;
 *   • `.pty-pair-offer` — код привязки в выводе `remotai pair`, уходит после
 *     привязки или отмены.
 * НЕ перекрытие, а вместимость (один честный resize):
 *   • `.pty-ssh-banner` — задан адресом (`?install=1`) и стоит с первого кадра
 *     вида до нажатия ✕: это начальная вёрстка, а не пришедшая плашка. Сдвиг
 *     спрятал бы верх сетки на всё время баннера, а install.sh печатает там QR
 *     привязки — его обрезать нельзя;
 *   • `.pty-dead-bar` — процесс завершён: перерисовывать нечего, и полоса стоит
 *     до переоткрытия, то есть это последняя вёрстка сеанса;
 *   • постоянная вёрстка (строка папки в шапке, ряды клавиш, блок «Запустить
 *     ИИ-агента»).
 */
export const OCCLUDER_SELECTORS: readonly string[] = [
  ".pty-agent-ask", ".pty-upload-strip", ".pty-width-notice", ".pty-update-bar", ".pty-pair-offer",
];

/**
 * РОСТ ПОЛЯ ВВОДА — ТОЖЕ ПЕРЕКРЫТИЕ (ST-08, справка S4 H4).
 *
 * Длинный промпт растит textarea с одной строки до пяти (+80 px), отправка
 * возвращает её обратно. Считать это вместимостью значит отдать агенту два
 * resize на каждый длинный промпт — две полные перерисовки TUI, у Claude Code
 * с дублями в прокрутке. Замер S4: пустых кадров рост поля не даёт, это не
 * мигание, а геометрия; решено — перекрытие, как плашка.
 *
 * Рост = высота панели ввода сейчас минус её высота при ОДНОЙ строке. Базы ещё
 * нет (поле открыли уже многострочным, например черновиком) — роста не видим:
 * такое изменение идёт прежним путём вместимости, выдумывать базу хуже.
 */
export function inputGrowthPx(textRows: number, barPx: number, oneRowBarPx: number): number {
  if (!Number.isFinite(textRows) || textRows <= 1) return 0;
  if (!Number.isFinite(barPx) || !Number.isFinite(oneRowBarPx) || oneRowBarPx <= 0) return 0;
  return Math.max(0, barPx - oneRowBarPx);
}

/** Explain a visibly narrow shared grid on a wide viewer, not small fit rounding. */
export function shouldExplainNarrowOutput(terminalCols: number, availableCols: number): boolean {
  return isSize(terminalCols) && isSize(availableCols) && availableCols >= 80
    && availableCols - terminalCols >= 16 && terminalCols < availableCols * 0.85;
}

/**
 * ПОЛНАЯ ВЫСОТА ЭКРАНА В ТЕКУЩЕЙ ОРИЕНТАЦИИ ОКНА — база, от которой считается
 * «клавиатура поднята».
 *
 * ⚠ ЖИВОЙ ДЕФЕКТ (iPad владельца, 10.09.2026). Брать `screen.height` как есть
 * нельзя: на планшете в ЛАНДШАФТЕ Safari продолжает отдавать портретные
 * размеры экрана. Боевая диагностика: `screen=820x1180 win=1180x820
 * vp=1180x820` — окно честно лежит на боку, а экран рапортует стоя. База
 * становилась 1180 при вьюпорте 820, и клиент вечно считал, что открыта
 * клавиатура: `клавиатура=true`, `reported=-1`. Отправка размера при
 * клавиатуре молчит по построению, поэтому PTY навсегда оставался таким,
 * каким его сделал последний узкий зритель (48×25 с телефона), а «Переоткрыть
 * терминал» не помогало — при пересоздании повторялся тот же расчёт.
 *
 * Ориентацию определяем по ШИРИНЕ окна относительно сторон экрана, а не по
 * тому, что окно шире, чем выше. ⚠ Второе кажется очевидным и неверно: с
 * поднятой клавиатурой портретное окно 390×380 тоже «шире, чем выше», и три
 * пробы клавиатуры честно поймали эту ошибку. Ширина же при клавиатуре не
 * меняется вовсе — это и есть надёжный признак: она совпадает с длинной
 * стороной экрана в ландшафте и с короткой в портрете.
 *
 * На десктопе базой остаётся сам вьюпорт: окно меньше монитора — это норма,
 * а не поднятая клавиатура.
 */
/**
 * Клавиатура поднята? — при наличии сигнала Android (Capacitor Keyboard).
 *
 * Сигнал «скрыта» — последнее СОБЫТИЕ, а не текущее состояние. После возврата
 * в приложение из фона Android снова поднимает клавиатуру над полем ввода, но
 * keyboardWillShow может прийти позже первого замера или не прийти вовсе.
 * Журнал 23–25.09.2026: 30 раз подряд переподключение с resume сразу слало
 * компьютеру 48×10 (вьюпорт 561 при базе 933), Claude перерисовывался под
 * 10 строк и через секунды ещё раз под 25. Поэтому «скрыта» перекрывается
 * замером: при той же ширине вьюпорт ниже базы на клавиатурный порог —
 * клавиатура на экране. Сигнал «поднята» верен всегда.
 */
export function nativeKeyboardOpen(
  native: boolean, viewportH: number, viewportW: number,
  baseH: number, baseW: number, minPx: number,
): boolean {
  if (native) return true;
  if (!isSize(baseH) || Math.abs(viewportW - baseW) >= 2) return false;
  return viewportH < baseH - minPx;
}

export function fullViewportHeight(
  viewportW: number, viewportH: number,
  screenW: number, screenH: number, coarsePointer: boolean,
): number {
  if (!coarsePointer || !isSize(screenW) || !isSize(screenH)) return viewportH;
  const long = Math.max(screenW, screenH);
  const short = Math.min(screenW, screenH);
  const landscape = Math.abs(viewportW - long) < Math.abs(viewportW - short);
  return landscape ? short : long;
}

/**
 * СВЕЖЕЕ ЛИ СОДЕРЖИМОЕ КАДРА ТОГО, ЧТО УЖЕ ПОКАЗАНО.
 *
 * Кадр снимается на позиции потока `base_offset`: всё до неё он уже содержит.
 * Сравнивать надо с тем, что человек уже ВИДИТ — с позицией, разобранной
 * xterm (`appliedOffsetRef`), а не с принятыми байтами. Принятые, но ещё
 * лежащие за барьером снапшота байты картинку не меняли, и кадр по ним
 * устаревшим не считается (до 2.61.16 считался — каждое пятое открытие
 * терминала оставалось без кадра). Если кадр снят раньше, чем то, что человек
 * уже видит, применять его нельзя: он откатит картинку назад, а откаченные
 * байты второй раз не придут (повторный аудит, T259-07).
 *
 * ⚠ Это НЕ замена серверной резке пачки по базе — та убирает саму гонку. Здесь
 * страховка на случай старого агента, сторожевого кадра и любого будущего пути
 * мимо резки: пришло старьё — не применяем и просим свежий.
 *
 * `base` отсутствует (старый агент) → решать нечем, применяем как раньше.
 */
export function frameIsStale(base: number | undefined, accepted: number): boolean {
  if (typeof base !== "number" || !Number.isFinite(base) || base <= 0) return false;
  return base < accepted;
}

/** Итог сверки сетки, принятой из кадра, с /state (reconcileAdoptedGrid). */
export type AdoptedGridCheck = {
  /** Сверка состоялась: снять пометку «сетка из кадра» (согласен /state или нет). */
  consumed: boolean;
  /** По высоте /state возражает: проверить сетку свежим кадром. */
  rows: boolean;
  /** По ширине /state возражает: проверить сетку свежим кадром. */
  cols: boolean;
};

/** A state request made before a confirmed frame cannot replace its grid. */
export function stateGridIsFresh(frameAt: number | null, stateAskedAt: number): boolean {
  return frameAt === null || (Number.isFinite(stateAskedAt) && stateAskedAt > frameAt);
}

/**
 * СЕТКА, ПРИНЯТАЯ ИЗ КАДРА, ЖИВЁТ ТОЛЬКО ДО ПЕРВОГО /state, СПРОШЕННОГО ПОСЛЕ НЕЁ
 * (ST-08, ревью скептика).
 *
 * Кадр на запрос после доставленной вместимости — сетка PTY (adopt в
 * frameGeometryAction), и клиент пишет её в авторитетную сетку сам. Но PTY
 * общий и меняется дальше, а сверка с /state шла только по ИЗМЕНЕНИЮ значения
 * /state. Если PTY вернулся к прежнему размеру, а /state промежуточного не
 * видел (скрытая вкладка /state не опрашивает), сетка залипала в чужом
 * размере: компьютер 47 колонок при PTY 123 после ухода телефона, и никто её
 * не исправлял — на проводе после показа вкладки пусто.
 *
 * Правило: первый /state, запрос которого ушёл ПОЗЖЕ приёма сетки из кадра,
 * её сверяет. Порядок гарантирован: сервер снял кадр раньше, чем клиент его
 * принял, а ответ на запрос, ушедший после этого, — ещё позже. Значит, /state
 * отражает PTY не старше кадра, и расхождение означает, что PTY сменился после
 * кадра. /state, спрошенный РАНЬШЕ приёма, ничего не доказывает (он мог
 * застать PTY до кадра) — иначе сетка качалась бы «кадр → старый /state → кадр».
 *
 * ⚠ РАСХОЖДЕНИЕ НЕ ЗНАЧИТ, ЧТО ПРАВ /state. Сетку по нему НЕ меняем, а просим
 * кадр: кадр на запрос после доставленной вместимости сам принесёт сетку PTY
 * (adopt), а совпавший — просто запишется, без resize. /state говорит лишь
 * «сетка могла смениться». Замер ревью: мок A01 отдаёт кадры в 20 строк при
 * /state 30 — первая редакция сверки брала 30, кадр возвращал 20, и сетка
 * качалась раз в опрос; каждый resize xterm отменял жест, навигационные пробы
 * падали 2 из 2 прогонов (до сверки — 2 из 2 зелёные).
 *
 * Сверка одноразовая на приём: пометку снимает любой ответ /state, спрошенный
 * после приёма, — согласие (дальше сетку держат эффекты state.rows/state.cols)
 * и расхождение (кадр запрошен ровно один раз; если он опять примет сетку,
 * пометка встанет заново вместе с ним). Значения /state нет (старый агент) —
 * сверять нечем, пометка остаётся.
 */
export function reconcileAdoptedGrid(s: {
  /** Момент приёма сетки из кадра; null — не принималась или уже сверена. */
  adoptedAt: number | null;
  /** Момент, когда ушёл запрос этого /state (те же часы, что adoptedAt). */
  stateAskedAt: number;
  stateCols?: number;
  stateRows?: number;
  /** Авторитетная сетка клиента сейчас (колонки и строки). */
  gridCols: number;
  gridRows: number;
}): AdoptedGridCheck {
  const none: AdoptedGridCheck = { consumed: false, rows: false, cols: false };
  if (s.adoptedAt === null || !Number.isFinite(s.stateAskedAt) || !(s.stateAskedAt > s.adoptedAt)) return none;
  const knownRows = isSize(s.stateRows);
  const knownCols = isSize(s.stateCols);
  if (!knownRows && !knownCols) return none;
  return {
    consumed: true,
    rows: knownRows && s.stateRows !== s.gridRows,
    cols: knownCols && s.stateCols !== s.gridCols,
  };
}
