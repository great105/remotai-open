/**
 * Клавиатура удалённого управления: что нажимается на ПК, а что печатается.
 *
 * Правила ввода жили внутри RemoteView.tsx. Они чистые (строка на входе,
 * решение на выходе) и ошибаются заметно: сочетание, набранное в кириллической
 * раскладке, уходило на компьютер пустым нажатием, а Ctrl+C внутри строки ввода
 * мог улететь на ПК вместо копирования на телефоне.
 */

/**
 * Сочетания с Ctrl, которые внутри строки ввода обслуживает сам браузер
 * (выделить всё / копировать / вставить / вырезать / отменить) — их не
 * перехватываем и на ПК не форвардим. Сверяем по e.code: на кириллической
 * раскладке Ctrl+C приходит как key «с», а браузер всё равно копирует по
 * физической клавише. По key — только фолбэк для клавиатур без code.
 */
export const localEditCodes = new Set(["KeyA", "KeyC", "KeyV", "KeyX", "KeyZ"]);
export const localEditKeys = new Set(["a", "c", "v", "x", "z"]);

/**
 * ЙЦУКЕН → QWERTY по ФИЗИЧЕСКОМУ положению клавиши. Сочетание человек набирает
 * в своей раскладке (Ctrl+«с» вместо Ctrl+C), а на ПК обязана уйти латинская
 * буква той же клавиши: у кириллического символа виртуального кода нет вовсе
 * (keyToVK → 0), и нажатие пропадало молча.
 */
export const layoutToLatin: Record<string, string> = {
  "й": "q", "ц": "w", "у": "e", "к": "r", "е": "t", "н": "y", "г": "u", "ш": "i",
  "щ": "o", "з": "p", "х": "[", "ъ": "]",
  "ф": "a", "ы": "s", "в": "d", "а": "f", "п": "g", "р": "h", "о": "j", "л": "k",
  "д": "l", "ж": ";", "э": "'",
  "я": "z", "ч": "x", "с": "c", "м": "v", "и": "b", "т": "n", "ь": "m",
  "б": ",", "ю": ".", "ё": "`",
};

/**
 * Печатный символ вне ASCII: агент такую клавишу не умеет нажать (нет VK / нет
 * X keysym), поэтому её надо не «нажимать», а ПЕЧАТАТЬ ({t:"txt"}).
 */
export function isNonAsciiChar(key: string): boolean {
  return Array.from(key).length === 1 && key.charCodeAt(0) > 127;
}

/** base64 из ответа агента → Blob для «Поделиться»/скачивания. */
export function base64ToBlob(base64: string, mime: string): Blob {
  const binary = atob(base64);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
  return new Blob([bytes], { type: mime });
}
