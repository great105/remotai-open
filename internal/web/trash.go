package web

import "errors"

// Корзина вместо os.Remove (находка «файл удаляется за 900 мс удержания»).
//
// ЗАЧЕМ. Удаление файла в клиенте — удержание кнопки 900 мс, без второго
// вопроса: палец, положенный на «Удалить» чтобы протащить ленту действий,
// уничтожал файл безвозвратно. Корзина делает это обратимым, а там, где
// корзины нет (сетевой диск, флешка, сервер без XDG), интерфейс обязан
// сказать правду — «удалено безвозвратно», а не обещать возврат.
//
// Реализация платформенная: trash_windows.go (SHFileOperationW +
// FOF_ALLOWUNDO → «Корзина»), trash_linux.go (freedesktop.org Trash spec:
// ~/.local/share/Trash + .trashinfo), trash_other.go (нет корзины).

// trashResult — куда на самом деле уехало удалённое.
type trashResult struct {
	// Kind — «recycle_bin» (Windows) или «freedesktop» (Linux). Уезжает
	// клиенту как есть: тексты у корзин разные («в Корзине» / «в корзине»).
	Kind string
	// RestorePath — где файл лежит СЕЙЧАС. Непустой только когда вернуть его
	// можно обычным перемещением (freedesktop): по нему клиент рисует
	// «Отменить» в тосте. Для «Корзины» Windows пусто — вернуть оттуда без
	// COM-оболочки shell нельзя, и обещать возврат мы не имеем права.
	RestorePath string
}

// errTrashUnsupported — на этой платформе/томе корзины нет. Не ошибка
// удаления: вызывающий удаляет как раньше и честно об этом сообщает.
var errTrashUnsupported = errors.New("trash is not available here")
