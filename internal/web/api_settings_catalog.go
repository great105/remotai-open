// Каталог настроек: что вообще можно настроить и что каждая настройка значит.
//
// ЗАЧЕМ. Просьба владельца: «человек запустил Claude на своём компьютере и
// говорит — давай посмотрим настройки, сделаем всё». Чтобы агент мог это
// сделать, он должен НЕ УГАДЫВАТЬ: какие есть ключи, что они означают, какие
// значения допустимы и что менять опасно. Поэтому источник правды — здесь, а
// `remotai config` только печатает то, что отдал агент.
//
// ГЛАВНОЕ СЛЕДСТВИЕ: новая настройка появляется у агента сама, без правок
// скилла и без обновления его знаний. Ровно то же правило, что у флагов
// запуска и `account_env`: реестр знает, клиент (и агент) не хардкодит.
//
// РИСК — не украшение, а граница власти. Владелец выбрал модель «безопасное
// агент меняет сам, опасное — только с подтверждением человека», и признак
// риска здесь — единственное место, где эта граница записана.
type SettingRisk string

const (
	// RiskSafe — легко заметить и откатить: не тем агентом запустится терминал,
	// придут лишние уведомления. Такое агент меняет сам.
	RiskSafe SettingRisk = "safe"
	// RiskDangerous — может отрезать человека от компьютера или потерять
	// доступ: облако, автозапуск, порт, привязка. Только с подтверждением.
	RiskDangerous SettingRisk = "dangerous"
)

// SettingSpec описывает одну настройку так, чтобы её понял и человек, и агент.
type SettingSpec struct {
	Key string `json:"key"`
	// Title — как называется словами человека («Агент по умолчанию»).
	Title string `json:"title"`
	// Hint — что произойдёт, если изменить. Одна строка, без жаргона.
	Hint string `json:"hint"`
	// Type — bool | string | int | path.
	Type string `json:"type"`
	// Options — допустимые значения (пусто = произвольное).
	Options []string    `json:"options,omitempty"`
	Risk    SettingRisk `json:"risk"`
	// Details — что это такое и как работает, человеческим языком.
	//
	// ЗАЧЕМ (владелец, 09.08.2026): «везде должны быть понятные пояснения —
	// например, что такое папка по умолчанию, что такое агент по умолчанию,
	// куда это идёт, как это работает». Однострочного Hint для этого мало: он
	// отвечает «что изменится», а не «что это вообще такое».
	//
	// Показывается, когда человек раскрыл настройку, — короткий список остаётся
	// коротким, а объяснение есть у каждой. Абзацами, а не простынёй.
	Details []string `json:"details,omitempty"`
	// Value — текущее значение, заполняется при выдаче.
	Value any `json:"value,omitempty"`
}

// vpnWatchdogKnownLine — строка со списком VPN-клиентов, которых знает сторож.
//
// Ответ на прямой вопрос владельца «а как он выбирает, какой VPN?»: никак не
// выбирает — список явный и короткий (см. netwatch.KnownVPNNames). Эвристик
// вроде «в имени есть vpn» там нет намеренно: сторож выключает чужую
// программу, и ошибка стоила бы человеку рабочего соединения.
//
// Список берётся из того же места, где живёт сама проверка, а не переписан
// сюда руками: иначе новый клиент появится в сторожа и не появится в
// объяснении.
func vpnWatchdogKnownLine() []string {
	names := netwatch.KnownVPNNames()
	if len(names) == 0 {
		return nil
	}
	return []string{strings.Join(names, " · ") + ". Другие туннели он не трогает."}
}

