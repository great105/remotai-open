// settingValue возвращает текущее значение настройки.
func settingValue(cfg *config.Config, key string) any {
	switch key {
	case "default_agent":
		return cfg.DefaultAgent
	case "default_cwd":
		return cfg.DefaultCwd
	case "notifications_enabled":
		return !strings.EqualFold(strings.TrimSpace(cfg.NotificationsEnabled), "false")
	case "detect_agent_questions":
		return cfg.DetectAgentQuestions
	case "shell_integration":
		return cfg.ShellIntegration
	case "agent_summaries":
		return cfg.AgentSummaries
	case "vpn_watchdog":
		return cfg.VPNWatchdogEnabled()
	case "peer_access":
		return relay.NormalizePeerAccess(cfg.PeerAccess)
	case "inbox_dir":
		return cfg.InboxDir
	case "max_concurrent_sessions":
		return cfg.MaxConcurrentSessions
	case "web_port":
		return cfg.Port()
	case "autostart":
		return getAutostartState().Enabled
	case "cloud":
		// Привязка есть, если у устройства сохранён ключ: именно он делает
		// компьютер видимым в приложении.
		return relay.Available()
	}
	return nil
}

// GET /api/settings/catalog — карта настроек для агента и панели.
//
// Отдаём и описание, и текущее значение одним ответом: агенту нужно и то и
// другое, а два запроса он склеит с рассинхроном.
func (s *Server) apiSettingsCatalog(w http.ResponseWriter, r *http.Request, uid int64) {
	cfg := config.GetNoSetup()
	list := settingsCatalog()
	for i := range list {
		list[i].Value = settingValue(cfg, list[i].Key)
	}
	jsonResp(w, map[string]any{
		"settings": list,
		// Пояснение к границе власти — в самом ответе: агент читает его до
		// того, как попробует что-то поменять, и не тратит попытку.
		"risk_note": "safe — можно менять самому; dangerous — только с подтверждением владельца (POST /api/settings/request)",
	})
}

// validateSetting проверяет значение до записи: агент присылает строку, а
// человеку потом жить с результатом.
func validateSetting(spec SettingSpec, raw string) (any, error) {
	value := strings.TrimSpace(raw)
	switch spec.Type {
	case "bool":
		switch strings.ToLower(value) {
		case "true", "1", "да", "on", "вкл":
			return true, nil
		case "false", "0", "нет", "off", "выкл":
			return false, nil
		}
		return nil, fmt.Errorf("нужно true или false")
	case "int":
		n, err := strconv.Atoi(value)
		if err != nil || n < 0 {
			return nil, fmt.Errorf("нужно целое число ≥ 0")
		}
		return n, nil
	case "string":
		if len(spec.Options) > 0 && !contains(spec.Options, value) {
			return nil, fmt.Errorf("допустимые значения: %s", strings.Join(spec.Options, ", "))
		}
		if value == "" {
			// Пустая строка там, где ждут имя, — почти всегда промах агента, а
			// не намерение: пустой `default_agent` ломает кнопку запуска.
			return nil, fmt.Errorf("нужно непустое значение")
		}
		return value, nil
	default: // path и всё остальное — как есть
		return value, nil
	}
}

func contains(list []string, v string) bool {
	for _, item := range list {
		if item == v {
			return true
		}
	}
	return false
}

// findSetting ищет описание по ключу.
func findSetting(key string) (SettingSpec, bool) {
	for _, spec := range settingsCatalog() {
		if spec.Key == key {
			return spec, true
		}
	}
	return SettingSpec{}, false
}
