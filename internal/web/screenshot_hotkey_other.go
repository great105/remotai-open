package web

// Горячая клавиша снимка экрана — пока только Windows.
//
// Честная заглушка вместо тихого «включено, но ничего не происходит»:
// `screenshotHotkeyStatus` возвращает причину, каталог настроек её показывает,
// и человек на Mac или Linux видит «клавиша на этой системе не поддержана», а
// не молчащий тумблер.
//
// Почему не сделано сразу для всех: на macOS глобальная горячая клавиша — это
// либо Carbon `RegisterEventHotKey`, либо `CGEventTap`, и второй требует
// разрешения «Мониторинг ввода» (человек выдаёт его руками в системных
// настройках, и без него перехват молча не работает — то есть нужна отдельная
// работа по объяснению этого в интерфейсе). На Linux нет единого механизма:
// в X11 это `XGrabKey`, в Wayland — портал `GlobalShortcuts`, у каждого
// окружения свой. Кнопка 📷 в приложении работает на всех системах.
func setScreenshotHotkey(bool) {}

func screenshotHotkeyActive() bool { return false }

func screenshotHotkeyError() string { return "hotkey_unsupported" }
