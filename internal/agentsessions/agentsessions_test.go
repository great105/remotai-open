func TestMessagesCountedIncrementally(t *testing.T) {
	f := newFixture(t)
	ix := newTestIndex(t, "")
	if _, err := ix.List(context.Background(), f.roots, nil, Query{}); err != nil {
		t.Fatal(err)
	}
	if err := ix.CountPass(context.Background()); err != nil {
		t.Fatal(err)
	}
	items := byID(mustList(t, ix, f.roots, nil, Query{}))
	// Claude: /clear, настоящее сообщение, текстовый ответ. Не считаются:
	// isMeta, вызов инструмента, его результат, ветка субагента.
	if n := items[claudeSID].Messages; n == nil || *n != 3 {
		t.Fatalf("Claude: ждали 3 сообщения, получили %v", deref(n))
	}
	// Codex: сообщение человека и ответ; инструкции и окружение — нет.
	if n := items[codexSID].Messages; n == nil || *n != 2 {
		t.Fatalf("Codex: ждали 2 сообщения, получили %v", deref(n))
	}
	// Дописали — досчитывается только новое.
	fh, err := os.OpenFile(f.claudeMain, os.O_APPEND|os.O_WRONLY, 0)
	if err != nil {
		t.Fatal(err)
	}
	_, _ = fh.WriteString(line(t, claudeUser("И ещё поправь цвет", nil)))
	// Недописанная строка: её не считаем, пока нет перевода строки.
	_, _ = fh.WriteString(`{"type":"user","message":{"role":"user","content":"полстро`)
	fh.Close()
	later := f.base.Add(50 * time.Minute)
	_ = os.Chtimes(f.claudeMain, later, later)
	mustList(t, ix, f.roots, nil, Query{})
	if err := ix.CountPass(context.Background()); err != nil {
		t.Fatal(err)
	}
	items = byID(mustList(t, ix, f.roots, nil, Query{}))
	if n := items[claudeSID].Messages; n == nil || *n != 4 {
		t.Fatalf("после дописывания ждали 4, получили %v", deref(n))
	}
	if items[claudeSID].Title != "Почини кнопку входа на телефоне" {
		t.Fatalf("голова дописыванием не меняется: %q", items[claudeSID].Title)
	}
	fh, _ = os.OpenFile(f.claudeMain, os.O_APPEND|os.O_WRONLY, 0)
	_, _ = fh.WriteString("ка\"}}\n")
	fh.Close()
	_ = os.Chtimes(f.claudeMain, later.Add(time.Minute), later.Add(time.Minute))
	mustList(t, ix, f.roots, nil, Query{})
	_ = ix.CountPass(context.Background())
	items = byID(mustList(t, ix, f.roots, nil, Query{}))
	if n := items[claudeSID].Messages; n == nil || *n != 5 {
		t.Fatalf("дописанная строка должна посчитаться один раз: %v", deref(n))
	}
}

func deref(n *int) any {
	if n == nil {
		return nil
	}
	return *n
}

