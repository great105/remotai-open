// Сообщения считаются только у бесед отданной страницы: полный проход по всем
// файлам на ПК владельца — это ~13 ГБ чтения после каждого запуска Remotai.
func TestCountPassOnlyVisiblePage(t *testing.T) {
	f := newFixture(t)
	ix := newTestIndex(t, "")
	page := mustList(t, ix, f.roots, nil, Query{Limit: 1})
	if len(page.Sessions) != 1 || page.Total < 2 {
		t.Fatalf("нужна страница из одной беседы при нескольких: %+v", page)
	}
	if err := ix.CountPass(context.Background()); err != nil {
		t.Fatal(err)
	}
	counted := 0
	for _, it := range mustList(t, ix, f.roots, nil, Query{}).Sessions {
		if it.Messages != nil {
			counted++
			if it.SessionID != page.Sessions[0].SessionID {
				t.Fatalf("посчитана беседа вне страницы: %s", it.SessionID)
			}
		}
	}
	if counted != 1 {
		t.Fatalf("посчитано %d бесед, ждали одну видимую", counted)
	}
}
