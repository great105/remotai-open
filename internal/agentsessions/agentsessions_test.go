func TestHumanText(t *testing.T) {
	cases := []struct{ in, title, cmd string }{
		{"Просто текст", "Просто текст", ""},
		{"<system-reminder>x</system-reminder>\n\nНастоящее", "Настоящее", ""},
		{"<local-command-stdout>вывод</local-command-stdout>", "", ""},
		{"<command-name>/review</command-name><command-args>PR 12</command-args>", "/review PR 12", ""},
		{"<command-name>/clear</command-name><command-args></command-args>", "", "/clear"},
		{"<pasted_content>длинная вставка", "", ""},
		{"# AGENTS.md instructions for /x", "", ""},
		{"[Request interrupted by user]", "", ""},
		{"   ", "", ""},
		{"Глянь скрин <image name=[Image #1]></image> и поправь", "Глянь скрин и поправь", ""},
	}
	for _, c := range cases {
		title, cmd := humanText(c.in)
		if title != c.title || cmd != c.cmd {
			t.Errorf("humanText(%q) = %q,%q; ждали %q,%q", c.in, title, cmd, c.title, c.cmd)
		}
	}
	long := strings.Repeat("я", 300)
	got, _ := humanText(long)
	if n := len([]rune(got)); n != titleRunes || !strings.HasSuffix(got, "…") {
		t.Fatalf("заголовок режется до %d символов с многоточием: %d", titleRunes, n)
	}
}

