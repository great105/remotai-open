func TestCacheByPathSizeMtime(t *testing.T) {
	f := newFixture(t)
	state := filepath.Join(t.TempDir(), "agent-sessions.json")
	ix := newTestIndex(t, state)
	mustList(t, ix, f.roots, nil, Query{})
	_ = ix.CountPass(context.Background())

	// Подменили содержимое, сохранив размер и время: читается кэш, а не файл.
	data, _ := os.ReadFile(f.codexMain)
	swapped := strings.Replace(string(data), "Сделай экран всех бесед", "Сделай экран ВСЕХ бесед", 1)
	if len(swapped) != len(data) {
		t.Fatal("подмена должна сохранить размер")
	}
	mod := f.base.Add(20 * time.Minute)
	write(t, f.codexMain, swapped, mod)
	if got := byID(mustList(t, ix, f.roots, nil, Query{}))[codexSID].Title; got != "Сделай экран всех бесед" {
		t.Fatalf("при тех же (размер, время) файл перечитываться не должен: %q", got)
	}

	// Кэш на диске: новый процесс не читает файлы заново, счётчики на месте.
	reopened := newTestIndex(t, state)
	items := byID(mustList(t, reopened, f.roots, nil, Query{}))
	if items[codexSID].Title != "Сделай экран всех бесед" || items[claudeSID].Messages == nil {
		t.Fatalf("кэш с диска не подхватился: %+v", items[codexSID])
	}

	// Файл переписан короче — разбираем с нуля.
	write(t, f.codexMain, line(t, map[string]any{"type": "session_meta", "payload": map[string]any{"id": codexSID, "cwd": "/new"}})+
		line(t, map[string]any{"type": "response_item", "payload": map[string]any{"type": "message", "role": "user",
			"content": []map[string]any{{"type": "input_text", "text": "Новая беседа"}}}}), mod.Add(time.Minute))
	items = byID(mustList(t, reopened, f.roots, nil, Query{}))
	if items[codexSID].Title != "Новая беседа" || items[codexSID].CWD != "/new" || items[codexSID].Messages != nil {
		t.Fatalf("переписанный файл: %+v", items[codexSID])
	}

	// Удалённый файл пропадает из списка и из кэша.
	_ = os.Remove(f.codexMain)
	if _, ok := byID(mustList(t, reopened, f.roots, nil, Query{}))[codexSID]; ok {
		t.Fatal("удалённая беседа осталась в списке")
	}
}

