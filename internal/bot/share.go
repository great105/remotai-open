// openFolder opens a directory in the host file manager.
//
// Окно здесь НЕ гасим: показать папку человеку у ПК — и есть смысл действия
// (кнопка «Открыть папку» в чате бота). Консольной вспышки тут и не бывает —
// explorer/open/xdg-open оконные, своей консоли не создают.
func openFolder(dir string) error {
	switch runtime.GOOS {
	case "windows":
		return exec.Command("explorer", dir).Start()
	case "darwin":
		return exec.Command("open", dir).Start()
	default:
		return exec.Command("xdg-open", dir).Start()
	}
}

// copyFile copies src to dst with default file mode.
func copyFile(src, dst string) error {
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()

	out, err := os.OpenFile(dst, os.O_WRONLY|os.O_CREATE|os.O_TRUNC, 0o644)
	if err != nil {
		return err
	}
	defer out.Close()

	buf := make([]byte, 64*1024)
	for {
		n, rerr := in.Read(buf)
		if n > 0 {
			if _, werr := out.Write(buf[:n]); werr != nil {
				return werr
			}
		}
		if rerr != nil {
			if rerr.Error() == "EOF" {
				return nil
			}
			break
		}
	}
	return nil
}

// buildViewCommand returns a shell-appropriate "view this file" command,
// including a trailing newline-less typing so the user reviews before pressing Enter.
func buildViewCommand(shellPath, fileRelPath string) string {
	low := strings.ToLower(filepath.Base(shellPath))
	switch {
	case strings.Contains(low, "powershell"), strings.Contains(low, "pwsh"):
		// PowerShell: Get-Content for text-like, Get-Item otherwise. Default to Get-Content.
		return fmt.Sprintf("Get-Content -Path \"%s\" | Select-Object -First 50", fileRelPath)
	case strings.Contains(low, "cmd"):
		return fmt.Sprintf("type \"%s\"", fileRelPath)
	default:
		// bash/zsh/fish — use cat with line limit.
		return fmt.Sprintf("head -n 50 \"%s\"", fileRelPath)
	}
}

// shortPath truncates very long paths for display in inline keyboard buttons.
func shortPath(p string) string {
	if len(p) <= 32 {
		return p
	}
	return "…" + p[len(p)-31:]
}

// shortShellName returns the basename of a shell path without extension.
func shortShellName(shell string) string {
	base := filepath.Base(shell)
	if ext := filepath.Ext(base); ext != "" {
		base = strings.TrimSuffix(base, ext)
	}
	return base
}
