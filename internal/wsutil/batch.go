package wsutil

import "time"

const (
	// BatchMax — порог размера пачки бинарных кадров вывода терминала.
	// ConPTY отдаёт вывод мелкими чанками (~72 байта на кадр репейнта Codex/Kimi),
	// и отправка каждого отдельным WS-сообщением превращала залп в 1,4 МБ в
	// ~20 тысяч фреймов со своим write-дедлайном на каждом из трёх плеч
	// (ПК → релей → телефон). 16 КБ — баланс: пачка заметно больше типичного
	// кадра репейнта, но всё ещё укладывается в пару TLS-записей.
	BatchMax = 16 << 10
	// BatchDelay — максимальное время накопления пачки. Интерактивное эхо
	// (одиночные нажатия) уходит с задержкой не хуже ~25 мс, что незаметно
	// на фоне сетевого RTT до телефона, а залповый репейнт за это окно
	// склеивается в десятки сообщений вместо тысяч.
	BatchDelay = 25 * time.Millisecond
)

// Batcher склеивает мелкие бинарные кадры терминала в пачки для отправки
// одним WS-сообщением. Порядок байт строго сохраняется: кадры только
// дописываются в хвост буфера. Текстовые JSON-маркеры в буфер не попадают —
// перед их отправкой писатель обязан сделать Flush (см. wsPtyHandler).
//
// Не потокобезопасен: живёт внутри одного пишущего цикла.
type Batcher struct {
	buf   []byte
	timer *time.Timer
}

// Add кладёт кадр в буфер. Первый кадр после Flush взводит таймер BatchDelay
// (канал — C()). Возвращает true, когда буфер достиг BatchMax и его пора
// сбрасывать, не дожидаясь таймера.
func (b *Batcher) Add(p []byte) (full bool) {
	if len(b.buf) == 0 {
		b.arm()
	}
	b.buf = append(b.buf, p...)
	return len(b.buf) >= BatchMax
}

// C — канал таймера накопления: select писателя ждёт его наравне с остальными
// событиями. Пока буфер пуст, возвращает nil (в select такой case просто
// не срабатывает).
func (b *Batcher) C() <-chan time.Time {
	if b.timer == nil {
		return nil
	}
	return b.timer.C
}

// Len — сколько байт накоплено сейчас.
func (b *Batcher) Len() int { return len(b.buf) }

// Flush возвращает накопленные байты и обнуляет буфер вместе с таймером.
// Возвращённый срез остаётся действительным до следующего Add — писатель
// успевает отдать его в сокет. На пустом буфере возвращает nil.
func (b *Batcher) Flush() []byte {
	out := b.buf
	b.buf = nil
	if b.timer != nil {
		if !b.timer.Stop() {
			// Таймер мог уже выстрелить — выбираем висевший тик, чтобы
			// следующее arm() не сбросилось раньше времени.
			select {
			case <-b.timer.C:
			default:
			}
		}
		b.timer = nil
	}
	return out
}

func (b *Batcher) arm() {
	if b.timer == nil {
		b.timer = time.NewTimer(BatchDelay)
		return
	}
	if !b.timer.Stop() {
		select {
		case <-b.timer.C:
		default:
		}
	}
	b.timer.Reset(BatchDelay)
}
