//go:build windows

package pty

import (
	"testing"

	"golang.org/x/sys/windows"
)

// Занятая труба — доказательство ЖИЗНИ хоста, а не его смерти: труба
// однопользовательская (nMaxInstances=1), и ответить «занято» может только
// работающий процесс. Цена ошибки известна: 31.07.2026 второй экземпляр агента
// за 23 секунды объявил «ждущими восстановления» все 16 живых терминалов
// владельца, потому что не различал ошибки дозвона.
//
// HostPID здесь ноль намеренно: вердикт обязан держаться на самой занятости,
// без опоры на PID, — запись могла устареть, а хост при этом жив.
func TestBusyPipeIsProofOfLife(t *testing.T) {
	alive, why := hostAliveAfterFailedDial(&hostRecord{HostPID: 0}, windows.ERROR_PIPE_BUSY)
	if !alive {
		t.Fatal("занятая труба принята за смерть хоста — терминал с работающим агентом будет похоронен")
	}
	if why != "труба занята" {
		t.Fatalf("причина обязана попадать в лог понятной, получили %q", why)
	}
}
