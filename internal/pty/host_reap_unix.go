// На POSIX добивания снаружи НЕТ — и это осознанно.
//
// Дерево терминала (шелл и всё, что человек в нём запустил) снимает сам хост:
// его Close делает kill(-pgid, SIGKILL) по группе шелла, потому что шелл
// запущен с Setsid и в группу хоста не входит (pty_linux.go / pty_darwin.go).
// SIGKILL, посланный хосту снаружи, этот путь минует: учётный процесс умрёт, а
// node/claude внутри останутся жить — уже без хоста, без записи и без единого
// признака в командной строке, по которому их можно было бы найти потом. То
// есть «страховка от утечки» на этих платформах утечку бы и создавала.
//
// Плюс на Linux со systemd в hostRecord лежит PID обёртки systemd-run, а не
// хоста: убивать по нему бессмысленно вдвойне, а гасить надо весь scope
// (stopScope). Чтобы сделать это правильно, нужен настоящий PID хоста и pgid
// шелла в hostRecord — отдельная задача, не для правки по следам инцидента на
// Windows.
func killHostProcess(string, uint32) bool { return false }

