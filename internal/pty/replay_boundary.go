package pty

import "sync"

// ГРАНИЦА ПЕРЕИГРОВКИ БУФЕРА: где кончается прошлое и начинается живой вывод.
//
// Подключаясь к хосту сессии, агент получает СНАЧАЛА буфер (кадры frSnapshot —
// то, что было напечатано до него), а потом живой поток (frOutput). Для чтения
// это один и тот же байтовый ручей, и до 2.57.15 сессия границы не видела вовсе.
//
// ⚠ ЧЕМ ЭТО ОБХОДИЛОСЬ ЧЕЛОВЕКУ. Зеркало экрана исполняет всё, что ему подают,
// как обычный поток: переигровка старого буфера гонит строки вверх, и они
// оседают в его scrollback — там, где настоящий терминал их бы не оставил.
// Живой замер 14.08.2026 (сессия 63dcb21f сразу после автообновления агента):
// в присланной телефону истории два повтора блока подряд — шапка
// `Claude Code v2.1.228` дважды и пара «цитата + пересылке.» дважды, ровно как
// на скриншоте владельца. Тот же поток через настоящий @xterm/headless даёт
// scrollback в четыре строки и НИ ОДНОГО повтора.
//
// Поэтому клиент хоста отмечает момент «переигровка кончилась», а сессия по
// этому сигналу отбрасывает scrollback, накопленный ИМЕННО переигровкой
// (см. Session.dropReplayScrollback). Цена принята владельцем осознанно: после
// перезапуска агента история агентских терминалов начинается заново — короткая,
// зато без дублей.
type replayWatch struct {
	mu   sync.Mutex
	fn   func()
	seen bool // видели кадр буфера
	done bool // граница уже объявлена
}

func (w *replayWatch) set(fn func()) {
	w.mu.Lock()
	w.fn = fn
	w.mu.Unlock()
}

// noteSnapshot — пришёл кусок переигровки.
func (w *replayWatch) noteSnapshot() {
	w.mu.Lock()
	w.seen = true
	w.mu.Unlock()
}

// noteOutput — пришёл живой вывод. Первый такой кадр ПОСЛЕ переигровки —
// ЗАПАСНОЙ признак границы для старого хоста, который frReplayEnd не шлёт.
func (w *replayWatch) noteOutput() {
	w.fire()
}

// noteReplayEnd — хост прислал явный кадр конца переигровки (frReplayEnd,
// 2.57.19+). Основной признак границы: он не зависит от того, напечатает ли
// сессия что-нибудь после снапшота, — у тихой сессии живого вывода может не
// быть вовсе (внешний аудит 2.57.18, находка P0-03). Без снапшота перед ним
// сигнал пустой: переигровки не было, и очищать нечего.
func (w *replayWatch) noteReplayEnd() {
	w.fire()
}

// fire объявляет границу ровно один раз на соединение и только если переигровка
// действительно была (seen).
func (w *replayWatch) fire() {
	w.mu.Lock()
	fn := w.fn
	fire := w.seen && !w.done
	if fire {
		w.done = true
	}
	w.mu.Unlock()
	if fire && fn != nil {
		fn()
	}
}
